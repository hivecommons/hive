var t0 = time.Date(2026, 10, 20, 12, 0, 0, 0, time.UTC)

func day(n int) time.Time { return t0.Add(time.Duration(n) * 24 * time.Hour) }

const stillOpen = 1 << 30

// pr builds a PRFiles open from day(open) to day(close); close==stillOpen
// leaves it open.
func pr(n, open, close int, files ...string) PRFiles {
	p := PRFiles{Repo: "o/r", Number: n, Files: files, OpenedAt: day(open), SeenAt: day(open)}
	if close != stillOpen {
		p.ClosedAt = day(close)
		p.Merged = true
	}
	return p
}

func goSource(groups int, lines int) []byte {
	var b strings.Builder
	b.WriteString("package p\n\n")
	for i := 0; i < groups; i++ {
		b.WriteString("type T" + string(rune('A'+i)) + " struct{}\n\n")
		b.WriteString("func (t *T" + string(rune('A'+i)) + ") M() {}\n\n")
	}
	for CountLines([]byte(b.String())) < lines {
		b.WriteString("//\n")
	}
	return []byte(b.String())
}

func reader(files map[string][]byte) SourceReader {
	return func(_, p string) (FileInfo, bool) {
		src, ok := files[p]
		if !ok {
			return FileInfo{}, false
		}
		return FileInfo{Lines: CountLines(src), Source: src}, true
	}
}

func TestAnalyzeThresholdsAndGuard(t *testing.T) {
	now := day(7)
	bigGo := goSource(6, 1000)
	smallGo := goSource(6, 200)
	oneGroup := goSource(1, 1000)
	files := map[string][]byte{
		"big.go":    bigGo,
		"small.go":  smallGo,
		"one.go":    oneGroup,
		"serial.go": bigGo,
	}
	// Six PRs all open concurrently on big.go, small.go, one.go → 15 pairs.
	var prs []PRFiles
	for i := 1; i <= 6; i++ {
		prs = append(prs, pr(i, 0, 5, "big.go", "small.go", "one.go"))
	}
	// serial.go: 6 PRs, none overlapping (each closed before the next opens).
	for i := 0; i < 6; i++ {
		prs = append(prs, pr(100+i, i, i, "serial.go"))
	}
	// few.go: only 3 PRs.
	for i := 0; i < 3; i++ {
		prs = append(prs, pr(200+i, 0, 5, "few.go"))
	}
	conflicts := []Conflict{{Repo: "o/r", Number: 1, Files: []string{"big.go"}, At: day(3)}}

	hs := Analyze("o/r", prs, conflicts, reader(files), Options{}, now)
	got := map[string]Hotspot{}
	for _, h := range hs {
		got[h.File] = h
	}
	if _, ok := got["serial.go"]; ok {
		t.Fatalf("serial.go has no concurrent pairs and must be excluded")
	}
	if _, ok := got["few.go"]; ok {
		t.Fatalf("few.go is below min_prs and must be excluded")
	}
	cases := []struct {
		file string
		rec  Recommendation
	}{
		{"big.go", RecommendSplitCode},
		{"small.go", RecommendNone},
		{"one.go", RecommendNone},
	}
	for _, c := range cases {
		h, ok := got[c.file]
		if !ok {
			t.Fatalf("%s missing from %+v", c.file, hs)
		}
		if h.PRs != 6 || h.Overlaps != 15 {
			t.Errorf("%s: prs=%d overlaps=%d, want 6/15", c.file, h.PRs, h.Overlaps)
		}
		if h.Recommendation != c.rec {
			t.Errorf("%s: recommendation %s (%s), want %s", c.file, h.Recommendation, h.Reason, c.rec)
		}
	}
	big := got["big.go"]
	if big.Conflicts != 1 {
		t.Errorf("big.go conflicts=%d want 1", big.Conflicts)
	}
	// 15 overlaps × 1.25 (≥800 lines) + 2×1 conflict.
	if want := 15*1.25 + 2; big.Score != want {
		t.Errorf("big.go score=%v want %v", big.Score, want)
	}
	if hs[0].File != "big.go" {
		t.Errorf("highest score first, got %s", hs[0].File)
	}
	if u := Units(big, Options{}); u != 4 {
		t.Errorf("Units=%d want 4 (capped)", u)
	}
	if u := Units(Hotspot{Lines: 400, SymbolGroups: []string{"a", "b", "c"}}, Options{}); u != 2 {
		t.Errorf("Units for 400 lines=%d want 2 (150-line floor)", u)
	}
}

func TestAnalyzeWindowExcludesOldPRs(t *testing.T) {
	var prs []PRFiles
	for i := 1; i <= 6; i++ {
		prs = append(prs, pr(i, -20, -15, "a.go")) // closed long before the window
	}
	hs := Analyze("o/r", prs, nil, nil, Options{}, day(0))
	if len(hs) != 0 {
		t.Fatalf("expected nothing in window, got %+v", hs)
	}
	// A still-open PR counts even if opened before the window.
	prs = nil
	for i := 1; i <= 6; i++ {
		prs = append(prs, pr(i, -20, stillOpen, "a.go"))
	}
	hs = Analyze("o/r", prs, nil, nil, Options{}, day(0))
	if len(hs) != 1 || hs[0].Recommendation != RecommendNone {
		t.Fatalf("open PRs: got %+v", hs)
	}
}

func TestAnalyzeKinds(t *testing.T) {
	md := []byte(strings.Repeat("## Section one\n\ntext\n\n## Section two\n\ntext\n", 300))
	smallMd := []byte("## A\n\n## B\n")
	gen := []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage p\n")
	files := map[string][]byte{
		"docs/api-reference.md":            md,
		"README.md":                        smallMd,
		"pkg/dashboard/static/index.html":  []byte(strings.Repeat("<div></div>\n", 2000)),
		"pkg/x/thing.pb.go":                gen,
		"go.sum":                           []byte("x\n"),
		"pkg/dashboard/static-src/js/a.js": []byte(strings.Repeat("function f(){}\n", 1000)),
		"pkg/dashboard/static-src/js/b.js": []byte("export function a(){}\nexport const b = 1;\nclass C {}\n" + strings.Repeat("//\n", 1000)),
	}
	var prs []PRFiles
	paths := make([]string, 0, len(files))
	for p := range files {
		paths = append(paths, p)
	}
	for i := 1; i <= 6; i++ {
		prs = append(prs, pr(i, 0, 5, paths...))
	}
	hs := Analyze("o/r", prs, nil, reader(files), Options{}, day(7))
	got := map[string]Hotspot{}
	for _, h := range hs {
		got[h.File] = h
	}
	want := map[string]struct {
		kind Kind
		rec  Recommendation
	}{
		"docs/api-reference.md":            {KindDoc, RecommendSplitDoc},
		"README.md":                        {KindDoc, RecommendReportOnly},
		"pkg/dashboard/static/index.html":  {KindGenerated, RecommendSplitSource},
		"pkg/x/thing.pb.go":                {KindGenerated, RecommendReportOnly},
		"go.sum":                           {KindLock, RecommendReportOnly},
		"pkg/dashboard/static-src/js/a.js": {KindCode, RecommendNone}, // one symbol group
		"pkg/dashboard/static-src/js/b.js": {KindCode, RecommendSplitCode},
	}
	for p, w := range want {
		h, ok := got[p]
		if !ok {
			t.Errorf("%s missing", p)
			continue
		}
		if h.Kind != w.kind || h.Recommendation != w.rec {
			t.Errorf("%s: kind=%s rec=%s (%s), want %s/%s", p, h.Kind, h.Recommendation, h.Reason, w.kind, w.rec)
		}
	}
	if g := got["pkg/dashboard/static/index.html"].GeneratedFrom; g != "pkg/dashboard/static-src/" {
		t.Errorf("GeneratedFrom=%q", g)
	}
	if g := got["docs/api-reference.md"].SymbolGroups; len(g) != 2 {
		t.Errorf("md sections=%v", g)
	}
	if g := got["pkg/dashboard/static-src/js/b.js"].SymbolGroups; len(g) != 3 {
		t.Errorf("js groups=%v", g)
	}
}

func TestGoGroupsCollapseMethodsIntoReceiver(t *testing.T) {
	src := []byte(`package p
type A struct{}
func (a *A) X() {}
func (a A) Y() {}
type B[T any] struct{}
func (b *B[T]) Z() {}
func Free() {}
var v = 1
`)
	g := Groups("x.go", src)
	if strings.Join(g, ",") != "A,B,Free" {
		t.Fatalf("groups=%v", g)
	}
	if Groups("x.go", []byte("package p\nfunc (")) != nil {
		t.Fatal("unparsable source must yield nil groups")
	}
}

type fakeCreator struct {
	calls  int
	title  string
	body   string
	labels []string
	err    error
}

func (f *fakeCreator) CreateHotspotIssue(_ context.Context, _, title, body string, labels []string) (int, string, error) {
	f.calls++
	f.title, f.body, f.labels = title, body, labels
	if f.err != nil {
		return 0, "", f.err
	}
	return 4000 + f.calls, "https://x/" + title, nil
}

type fakeStater struct {
	open     bool
	closedAt time.Time
}

func (f fakeStater) HotspotIssueState(context.Context, string, int) (bool, time.Time, error) {
	return f.open, f.closedAt, nil
}

type gateFn func(repo, file string) bool

func (g gateFn) IssueFileAllowed(repo, file string) bool { return g(repo, file) }

func hot() Hotspot {
	return Hotspot{
		Repo: "o/r", File: "pkg/dashboard/api.go", Kind: KindCode, PRs: 8, PRNumbers: []int{1, 2, 3, 4, 5, 6, 7, 8},
		Overlaps: 11, Conflicts: 2, Lines: 2400, Score: 20.5,
		SymbolGroups:   []string{"Server", "handleAgents", "handleConfig", "handleStatus", "statusWithWebhooks"},
		Recommendation: RecommendSplitCode, Reason: "large file with several top-level groups hit by concurrent PRs",
	}
}

func TestFilerDedupeAndRefileWindow(t *testing.T) {
	store, err := NewStore("")
	if err != nil {
		t.Fatal(err)
	}
	clock := day(0)
	now := func() time.Time { return clock }
	store.SetClock(now)
	cr := &fakeCreator{}
	st := &fakeStater{open: true}
	f := &Filer{Store: store, Creator: cr, Stater: st, Now: now, Refile: 30 * 24 * time.Hour}
	ctx := context.Background()
	h := hot()

	out := f.File(ctx, "o/r", []Hotspot{h})
	if out[0].Action != "filed" || cr.calls != 1 {
		t.Fatalf("first pass: %+v calls=%d", out, cr.calls)
	}
	if !strings.HasPrefix(cr.body, Marker(h.File)) {
		t.Errorf("body must start with dedupe marker, got %q", cr.body[:60])
	}
	if cr.title != "refactor: pkg/dashboard/api.go is a merge hotspot — split into 4 units" {
		t.Errorf("title=%q", cr.title)
	}
	if strings.Join(cr.labels, ",") != "agent/ci-maintainer,kind/cleanup" {
		t.Errorf("labels=%v", cr.labels)
	}

	// Still open → no second issue.
	out = f.File(ctx, "o/r", []Hotspot{h})
	if out[0].Action != "open" || cr.calls != 1 {
		t.Fatalf("open pass: %+v calls=%d", out, cr.calls)
	}

	// Closed 10 days ago, refile window 30 days → wait.
	clock = day(20)
	st.open, st.closedAt = false, day(10)
	out = f.File(ctx, "o/r", []Hotspot{h})
	if out[0].Action != "refile-wait" || cr.calls != 1 {
		t.Fatalf("refile-wait pass: %+v calls=%d", out, cr.calls)
	}
	if rec, _ := store.Issue("o/r", h.File); rec.ClosedAt != day(10) {
		t.Errorf("close not recorded: %+v", rec)
	}

	// Past the window → refile.
	clock = day(41)
	out = f.File(ctx, "o/r", []Hotspot{h})
	if out[0].Action != "filed" || cr.calls != 2 {
		t.Fatalf("refile pass: %+v calls=%d", out, cr.calls)
	}

	// Not actionable → skip; gated → gated.
	h2 := h
	h2.Recommendation = RecommendNone
	if out := f.File(ctx, "o/r", []Hotspot{h2}); out[0].Action != "skip" {
		t.Errorf("non-actionable: %+v", out)
	}
	h3 := h
	h3.File = "other.go"
	f.Gate = gateFn(func(string, string) bool { return false })
	if out := f.File(ctx, "o/r", []Hotspot{h3}); out[0].Action != "gated" || cr.calls != 2 {
		t.Errorf("gated: %+v calls=%d", out, cr.calls)
	}
	f.Gate = nil
	cr.err = errors.New("boom")
	if out := f.File(ctx, "o/r", []Hotspot{h3}); out[0].Action != "error" {
		t.Errorf("error: %+v", out)
	}
	if _, ok := store.Issue("o/r", "other.go"); ok {
		t.Error("failed create must not be recorded")
	}
}

