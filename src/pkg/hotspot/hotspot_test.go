func TestStorePersistAndPrune(t *testing.T) {
	p := filepath.Join(t.TempDir(), "h.json")
	s, err := NewStore(p)
	if err != nil {
		t.Fatal(err)
	}
	clock := day(0)
	s.SetClock(func() time.Time { return clock })
	s.ObservePR("o/r", 1, []string{"a.go"}, time.Time{})
	s.ObservePR("o/r", 2, []string{"a.go", "b.go"}, day(-1))
	s.ObserveConflict("o/r", 2, []string{"a.go"})
	s.ReconcileOpen("o/r", map[int]bool{2: true})
	s.RecordIssue(IssueRecord{Repo: "o/r", File: "a.go", Number: 9, FiledAt: clock})

	s2, err := NewStore(p)
	if err != nil {
		t.Fatal(err)
	}
	prs, cs := s2.Snapshot("o/r")
	if len(prs) != 2 || len(cs) != 1 {
		t.Fatalf("reload: prs=%d conflicts=%d", len(prs), len(cs))
	}
	if prs[0].Number != 1 || prs[0].ClosedAt.IsZero() || !prs[0].Merged {
		t.Errorf("PR 1 should be reconciled closed: %+v", prs[0])
	}
	if prs[1].ClosedAt.IsZero() == false {
		t.Errorf("PR 2 must stay open: %+v", prs[1])
	}
	if _, ok := s2.Issue("o/r", "a.go"); !ok {
		t.Error("issue record lost")
	}

	// Prune: PR 1 closed at day0; at day 10 with a 7-day window it goes.
	s2.SetClock(func() time.Time { return day(10) })
	s2.MarkIssueClosed("o/r", "a.go", day(1))
	s2.Prune(7*24*time.Hour, 30*24*time.Hour)
	prs, cs = s2.Snapshot("o/r")
	if len(prs) != 1 || prs[0].Number != 2 || len(cs) != 0 {
		t.Errorf("after prune: prs=%+v conflicts=%d", prs, len(cs))
	}
	if _, ok := s2.Issue("o/r", "a.go"); !ok {
		t.Error("issue closed 9 days ago must survive a 30-day refile prune")
	}
	s2.SetClock(func() time.Time { return day(40) })
	s2.Prune(7*24*time.Hour, 30*24*time.Hour)
	if _, ok := s2.Issue("o/r", "a.go"); ok {
		t.Error("issue closed 39 days ago must be pruned")
	}

	s2.SetResults("o/r", []Hotspot{{Repo: "o/r", File: "b.go", Score: 1, Recommendation: RecommendSplitCode}})
	if total, act, _ := s2.Counts(); total != 1 || act != 1 {
		t.Errorf("counts=%d/%d", total, act)
	}
}

func TestStoreExpireUnseenAndTouch(t *testing.T) {
	s, _ := NewStore("")
	clock := day(0)
	s.SetClock(func() time.Time { return clock })
	s.ObservePR("o/r", 1, []string{"a.go"}, time.Time{})
	s.ObservePR("o/r", 2, []string{"a.go"}, time.Time{})
	clock = day(0).Add(3 * time.Hour)
	s.TouchOpen("o/r", []int{2, 99})
	s.ExpireUnseen(2 * time.Hour)
	prs, _ := s.Snapshot("o/r")
	if len(prs) != 2 || prs[0].ClosedAt != day(0) || !prs[1].ClosedAt.IsZero() {
		t.Fatalf("expire: %+v", prs)
	}
	// Seen open again → interval reopens.
	s.ObservePR("o/r", 1, []string{"a.go"}, time.Time{})
	prs, _ = s.Snapshot("o/r")
	if !prs[0].ClosedAt.IsZero() || prs[0].OpenedAt != day(0) {
		t.Fatalf("reopen: %+v", prs[0])
	}
}

func TestGeneratedWithSplitSourceIsReportOnly(t *testing.T) {
	const out = "pkg/dashboard/static/index.html"
	files := map[string][]byte{out: []byte("<!-- Code generated by webstatic DO NOT EDIT -->\n")}
	var prs []PRFiles
	for i := 1; i <= 6; i++ {
		prs = append(prs, pr(i, 0, 5, out))
	}
	for _, c := range []struct {
		n   int
		rec Recommendation
	}{{120, RecommendReportOnly}, {2, RecommendSplitSource}} {
		opts := Options{SourceFileCount: func(_, dir string) int { return c.n }}
		hs := Analyze("o/r", prs, nil, reader(files), opts, day(7))
		if len(hs) != 1 || hs[0].Kind != KindGenerated {
			t.Fatalf("hotspots=%+v", hs)
		}
		h := hs[0]
		if h.Recommendation != c.rec {
			t.Errorf("n=%d: rec=%s (%s), want %s", c.n, h.Recommendation, h.Reason, c.rec)
		}
		if c.rec == RecommendReportOnly {
			if !strings.Contains(h.Reason, "already split into 120 files") {
				t.Errorf("reason=%q", h.Reason)
			}
			if h.Actionable() {
				t.Errorf("n=%d: report-only hotspot is actionable", c.n)
			}
		}
	}
}
