func TestClassifyGeneratedHeaderPointsAtSource(t *testing.T) {
	src := []byte("// Code generated by gen/main.go from static-src; DO NOT EDIT.\npackage p\n")
	kind, from := Classify("pkg/x/out.go", src)
	if kind != KindGenerated || from != "gen/main" {
		t.Fatalf("got %s/%q", kind, from)
	}
	if kind, _ := Classify("pkg/x/y.go", []byte("package p\n")); kind != KindCode {
		t.Fatalf("plain Go file classified %s", kind)
	}
	if kind, _ := Classify("config.yaml", nil); kind != KindData {
		t.Fatalf("yaml classified %s", kind)
	}
}

func TestCountLinesAndGroupsEdgeCases(t *testing.T) {
	if n := CountLines([]byte("a\nb")); n != 2 {
		t.Errorf("no trailing newline: %d", n)
	}
	if n := CountLines([]byte("a\nb\n")); n != 2 {
		t.Errorf("trailing newline: %d", n)
	}
	goSrc := []byte("package p\n\ntype G[T any] struct{}\n\nfunc (g G[T]) A() {}\nfunc (g *G[T]) B() {}\nfunc F() {}\nvar x = 1\n")
	g := Groups("pkg/p/g.go", goSrc)
	if strings.Join(g, ",") != "F,G" {
		t.Errorf("generic receiver groups=%v", g)
	}
	if g := Groups("pkg/p/bad.go", []byte("package p\nfunc {")); g != nil {
		t.Errorf("unparsable Go should give nil, got %v", g)
	}
	if g := Groups("a.py", []byte("def a():\n  pass\nclass B:\n  pass\nasync def c(): pass\n")); len(g) != 3 {
		t.Errorf("py groups=%v", g)
	}
	if g := Groups("a.rs", []byte("fn main() {}\n")); g != nil {
		t.Errorf("unknown language should give nil, got %v", g)
	}
	if g := Groups("a.go", nil); g != nil {
		t.Errorf("empty source should give nil, got %v", g)
	}
}

func TestUnitsAndTitle(t *testing.T) {
	cases := []struct {
		lines, groups, want int
	}{
		{800, 10, 4}, // capped at MaxUnits
		{400, 10, 2}, // floor of 2
		{800, 3, 3},  // never more units than groups
		{800, 0, 4},  // no symbol info: size only
	}
	for _, c := range cases {
		h := Hotspot{Lines: c.lines, SymbolGroups: make([]string, c.groups)}
		if got := Units(h, Options{}); got != c.want {
			t.Errorf("Units(lines=%d groups=%d)=%d want %d", c.lines, c.groups, got, c.want)
		}
	}
	h := Hotspot{File: "pkg/dashboard/stage_tracker.go"}
	if got := Title(h, 3); !strings.Contains(got, "stage_tracker.go") || !strings.Contains(got, "3 units") {
		t.Errorf("Title=%q", got)
	}
	if got := Title(Hotspot{File: "docs/x.md", Recommendation: RecommendSplitDoc}, 3); !strings.Contains(got, "3 sections") {
		t.Errorf("doc Title=%q", got)
	}
	h.Kind, h.GeneratedFrom, h.Recommendation = KindGenerated, "pkg/dashboard/static-src/", RecommendSplitSource
	if got := Title(h, 3); !strings.Contains(got, "static-src") {
		t.Errorf("generated Title should name the source: %q", got)
	}
}

func TestProposeBucketsShapes(t *testing.T) {
	many := make([]string, 0, 12)
	for i := 0; i < 12; i++ {
		many = append(many, "Group"+string(rune('A'+i)))
	}
	code := proposeBuckets(Hotspot{File: "pkg/p/big_test.go", Kind: KindCode, SymbolGroups: many}, 2)
	if len(code) != 2 || code[0].file != "pkg/p/big_test.go" || !strings.HasPrefix(code[1].file, "pkg/p/big_") {
		t.Fatalf("code buckets=%+v", code)
	}
	if !strings.Contains(code[0].desc, "more") {
		t.Errorf("bucket with >4 groups should elide: %q", code[0].desc)
	}
	sparse := proposeBuckets(Hotspot{File: "pkg/p/a.go", Kind: KindCode, SymbolGroups: []string{"Only"}}, 3)
	if sparse[2].desc != "remaining helpers" {
		t.Errorf("empty bucket desc=%q", sparse[2].desc)
	}
	doc := proposeBuckets(Hotspot{File: "docs/ops.md", Kind: KindDoc, SymbolGroups: []string{"Alpha / Beta", "Gamma", "Delta", "Epsilon", "Zeta"}}, 2)
	if len(doc) != 3 || doc[0].file != "docs/ops/README.md" || doc[1].file != "docs/ops/alpha_beta.md" {
		t.Fatalf("doc buckets=%+v", doc)
	}
	if !strings.Contains(doc[2].desc, "remaining sections") {
		t.Errorf("doc tail should count the rest: %q", doc[2].desc)
	}
	if s := slug("  Ünïcode--Name That Is Far Too Long To Keep  "); s != "n_code_name_that_is_far" && len(s) > 24 {
		t.Errorf("slug=%q", s)
	}
	if partName(5, []string{"a"}, 6) != "part6" {
		t.Error("partName fallback")
	}
}

func TestStoreClosePRReposAndResults(t *testing.T) {
	s, err := NewStore(filepath.Join(t.TempDir(), "h.json"))
	if err != nil {
		t.Fatal(err)
	}
	clock := day(0)
	s.SetClock(func() time.Time { return clock })
	s.ObservePR("o/r", 1, []string{"a.go"}, time.Time{})
	s.ObservePR("o/z", 7, []string{"z.go"}, time.Time{})
	s.ClosePR("o/r", 1, false, time.Time{})
	s.ClosePR("o/r", 1, true, day(3))  // already closed: no-op
	s.ClosePR("o/r", 99, true, day(3)) // unknown: no-op
	prs, _ := s.Snapshot("o/r")
	if len(prs) != 1 || !prs[0].ClosedAt.Equal(clock) || prs[0].Merged {
		t.Fatalf("ClosePR: %+v", prs)
	}
	if got := strings.Join(s.Repos(), ","); got != "o/r,o/z" {
		t.Errorf("Repos=%q", got)
	}
	s.RecordIssue(IssueRecord{Repo: "o/r", File: "a.go", Number: 5, URL: "u", FiledAt: clock})
	s.SetResults("o/r", []Hotspot{{Repo: "o/r", File: "a.go", Score: 1}, {Repo: "o/r", File: "b.go", Score: 9}})
	s.SetResults("o/z", []Hotspot{{Repo: "o/z", File: "z.go", Score: 9}})
	all := s.Results("")
	if len(all) != 3 || all[0].Score != 9 || all[1].Score != 9 || all[0].Repo != "o/r" || all[2].File != "a.go" {
		t.Fatalf("Results order=%+v", all)
	}
	if all[2].IssueNumber != 5 || all[2].IssueURL != "u" {
		t.Errorf("issue not joined onto result: %+v", all[2])
	}
	if one := s.Results("o/z"); len(one) != 1 || one[0].File != "z.go" {
		t.Errorf("Results(o/z)=%+v", one)
	}
}
