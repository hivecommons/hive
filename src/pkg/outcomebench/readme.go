package outcomebench

import (
	"errors"
	"fmt"
	"math"
	"strings"
)

// README markers; everything between them is owned by the generator.
const (
	ReadmeStart = "<!-- outcomes:start -->"
	ReadmeEnd   = "<!-- outcomes:end -->"
)

// ErrNoMarkers is returned when a README has no outcomes block to rewrite.
var ErrNoMarkers = errors.New("README has no " + ReadmeStart + " … " + ReadmeEnd + " block")

// ReadmeBlock renders the README evidence section for a general reader:
// one line of scale, then Accuracy / Security / Cost / Also, each a card
// (a <picture> with a dark and a light PNG) and at most two flat sentences,
// one of which states the limit of the number. No statistical vocabulary
// appears here; it lives in the report. docDir is the path from the README
// to the benchmark directory.
func (r Report) ReadmeBlock(docDir string) string {
	report := fmt.Sprintf("%s/outcomes-%s.md", docDir, r.Month())
	var lines []string
	add := func(s ...string) { lines = append(lines, s...) }
	cards := func(width int, names ...string) {
		var shown []string
		for _, n := range names {
			if r.HasCard(n) {
				shown = append(shown, r.picture(docDir, n, width))
			}
		}
		if len(shown) > 0 {
			add(shown...)
			add("")
		}
	}
	add(ReadmeStart)
	add(fmt.Sprintf("<!-- generated by src/scripts/outcome-benchmark.sh --readme. Do not edit by hand. Report: %s -->", report))
	add(r.HeroLine(), "")

	add("## Accuracy", "")
	if r.HasCard(CardAccuracy) || r.HasCard(CardStories) {
		if s, ok := r.accuracySentences(); ok {
			add(s, "")
		}
		cards(cardW, CardAccuracy, CardChecksGreen, CardStories)
	} else {
		add("Not enough reviewed pull requests are on record yet to say how accurate the review is.", "")
	}

	add("## Security", "")
	if s, ok := r.securitySentences(); ok {
		add(s, "")
	} else {
		add("Agents run as a GitHub App, not on your token.", "")
	}
	cards(cardW, CardPromptInjection)

	add("## Cost", "")
	if s, ok := r.costSentences(); ok {
		add(s, "")
		cards(cardW, CardCost)
	} else {
		add("Cost per merged pull request shows once enough Hive merges are on record.", "")
	}

	add("## And the rest", "")
	add(r.alsoSentences(), "")
	cards(cardW, CardAlso)

	add(fmt.Sprintf("Humans still merge. Start with \"open PRs only\". When you trust it, [turn it up](%s/acmm-policy-matrix.md) and it merges on green, like a merge queue that reads the code.", strings.TrimSuffix(docDir, "/benchmarks")), "")
	add(fmt.Sprintf("%s [How we count →](%s)", r.followupCaveat(), report))
	add(ReadmeEnd)
	return strings.Join(lines, "\n")
}

// followupCaveat is the one honest clause under the cards: shipped-code
// outcomes (reverts) are not shown because reviewed merges are too new.
func (r Report) followupCaveat() string {
	return "Reverts are too new to report."
}

// HeroLine is the one sentence of scale at the top of the README.
func (r Report) HeroLine() string {
	s := fmt.Sprintf("Everything below comes from %s live pull requests in %d repositories", commas(r.PRs), len(r.Repos))
	if r.Verdicts > 0 {
		s += fmt.Sprintf(" and %s reviews", commas(r.Verdicts))
	}
	return s + " " + monthLabel(r.GeneratedAt) + "."
}

// The section sentences repeat each card's finding as plain text, so the
// numbers are searchable and read aloud the way a person would say them.
// Each is a few short sentences with one idea apiece and no semicolons.

func (r Report) accuracySentences() (string, bool) {
	f := r.Followup
	fa, ta := f.FixedAndApproved, f.TimeToApproval
	if !fa.Reported || fa.K <= 0 || fa.N < r.MinBase() {
		return "", false
	}
	words := strings.ToUpper(shareWords(fa.Rate)[:1]) + shareWords(fa.Rate)[1:]
	s := fmt.Sprintf("The review agent sent %s pull requests back. %s came back fixed and approved", commas(fa.N), words)
	if ta.Reported && ta.N >= r.MinBase() {
		s += fmt.Sprintf(", usually within %d minutes", minutes(ta.Value))
	}
	return s + ".", true
}

func (r Report) securitySentences() (string, bool) {
	rt := r.RedTeam
	if rt == nil || rt.Attacks <= 0 {
		return "", false
	}
	fa := fmt.Sprintf("One harmless text in %d got flagged by mistake.", rt.Benign)
	if rt.FalseAlarms != 1 {
		fa = fmt.Sprintf("%d harmless texts in %d got flagged by mistake.", rt.FalseAlarms, rt.Benign)
	}
	return fmt.Sprintf("We planted %d texts that try to redirect an agent in issues and files. Hive caught %d before an agent read a word. %s Agents run as a GitHub App, not on your token.", rt.Attacks, rt.Caught, fa), true
}

func (r Report) costSentences() (string, bool) {
	per, ok := r.Spend.PerMergedPR()
	if !ok || r.Spend.MergedPRs < r.MinBase() {
		return "", false
	}
	fig := fmt.Sprintf("$%.0f", per)
	if per < 1 {
		fig = fmt.Sprintf("%d¢", int(math.Round(per*100)))
	}
	total := "$" + commas(int(math.Round(r.Spend.USD)))
	return fmt.Sprintf("Agents spent about %s to merge %s pull requests. Call it %s a merge, our estimate %s.", total, commas(r.Spend.MergedPRs), fig, rangeLabel(r.Spend.WindowStart, r.Spend.WindowEnd)), true
}

func (r Report) alsoSentences() string {
	s := "Every pull request gets the same one-line review, in your style guide's voice."
	if with, without, ok := r.speedBars(); ok && with > without {
		s += fmt.Sprintf(" It adds about %d minutes to a merge.", with-without)
	}
	return s
}

// picture is the GitHub-flavoured <picture> that swaps the card PNG with
// the reader's colour scheme; the alt text is the card's title sentence.
// The PNG, not the SVG, is embedded: see raster.go.
func (r Report) picture(docDir, card string, width int) string {
	alt := card
	if svg, ok := r.Card(card, cardThemes[0]); ok {
		if i, j := strings.Index(svg, "<title>"), strings.Index(svg, "</title>"); i >= 0 && j > i {
			alt = svg[i+len("<title>") : j]
		}
	}
	return fmt.Sprintf(`<picture><source media="(prefers-color-scheme: dark)" srcset="%s/assets/%s"><img alt="%s" width="%d" src="%s/assets/%s"></picture>`,
		docDir, r.CardPNGFile(card, "dark"), alt, width, docDir, r.CardPNGFile(card, "light"))
}

// HowItWorksPicture is the ladder card for the README's own section.
func (r Report) HowItWorksPicture(docDir string) string {
	return r.picture(docDir, CardHowItWorks, cardW)
}

// UpdateReadme replaces the marker block in readme with block. The block is
// expected to start with ReadmeStart and end with ReadmeEnd.
func UpdateReadme(readme, block string) (string, error) {
	start := strings.Index(readme, ReadmeStart)
	end := strings.Index(readme, ReadmeEnd)
	if start < 0 || end < start {
		return "", ErrNoMarkers
	}
	return readme[:start] + block + readme[end+len(ReadmeEnd):], nil
}

// ExtractReadmeBlock returns the current marker block, markers included.
func ExtractReadmeBlock(readme string) (string, error) {
	start := strings.Index(readme, ReadmeStart)
	end := strings.Index(readme, ReadmeEnd)
	if start < 0 || end < start {
		return "", ErrNoMarkers
	}
	return readme[start : end+len(ReadmeEnd)], nil
}
