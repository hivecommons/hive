package outcomebench

import (
	"errors"
	"fmt"
	"strings"
)

// README markers; everything between them is owned by the generator.
const (
	ReadmeStart = "<!-- outcomes:start -->"
	ReadmeEnd   = "<!-- outcomes:end -->"
)

// ErrNoMarkers is returned when a README has no outcomes block to rewrite.
var ErrNoMarkers = errors.New("README has no " + ReadmeStart + " … " + ReadmeEnd + " block")

// ReadmeBlock renders the README "Outcomes" section: 3–4 bold headline
// numbers, each with n and date and a one-line "how measured", plus the two
// generated charts. Only reported figures appear; docDir is the path from
// the README to the benchmark directory.
func (r Report) ReadmeBlock(docDir string) string {
	report := fmt.Sprintf("%s/outcomes-%s.md", docDir, r.Month())
	var lines []string
	add := func(s string) { lines = append(lines, s) }
	add(ReadmeStart)
	add(fmt.Sprintf("<!-- generated by src/scripts/outcome-benchmark.sh --readme; do not edit by hand. Report: %s -->", report))
	m, u := r.Mediated, r.Unmediated
	asOf := day(r.GeneratedAt)
	if r.SplitSupported() {
		if m.ChangesRequested.Reported {
			add(fmt.Sprintf("- **%.0f%% of reviewed PRs were flagged for changes before they merged** — a `changes_requested` verdict on an earlier head of %d of %d mediated merges [%.1f–%.1f], %s.",
				100*m.ChangesRequested.Rate, m.ChangesRequested.K, m.ChangesRequested.N, 100*m.ChangesRequested.Lo, 100*m.ChangesRequested.Hi, asOf))
		}
		if m.RevertRate.Reported && u.RevertRate.Reported {
			add(fmt.Sprintf("- **Revert rate %.1f%% mediated vs %.1f%% unmediated** — %d/%d vs %d/%d merges matured %d days, Wilson [%.1f–%.1f] vs [%.1f–%.1f], %s.",
				100*m.RevertRate.Rate, 100*u.RevertRate.Rate, m.RevertRate.K, m.RevertRate.N, u.RevertRate.K, u.RevertRate.N, int(Maturation.Hours()/24),
				100*m.RevertRate.Lo, 100*m.RevertRate.Hi, 100*u.RevertRate.Lo, 100*u.RevertRate.Hi, asOf))
		}
		if m.TimeToMerge.Reported && u.TimeToMerge.Reported {
			add(fmt.Sprintf("- **Median time-to-merge %.0f min mediated vs %.0f min unmediated** — review costs about %.0f minutes on the median PR (n=%d vs %d), %s.",
				60*m.TimeToMerge.Value, 60*u.TimeToMerge.Value, 60*(m.TimeToMerge.Value-u.TimeToMerge.Value), m.TimeToMerge.N, u.TimeToMerge.N, asOf))
		}
	} else {
		add(fmt.Sprintf("- The current evidence does not support a mediated-vs-unmediated comparison (mediated n=%d, unmediated n=%d); only scale facts are shown.", m.Merged, u.Merged))
	}
	if per, ok := r.Spend.PerMergedPR(); ok {
		add(fmt.Sprintf("- **≈$%.2f estimated agent spend per merged PR** — `/api/cost` estimate over %d hive-attributed merges, %s → %s.", per, r.Spend.MergedPRs, day(r.Spend.WindowStart), day(r.Spend.WindowEnd)))
	}
	add(fmt.Sprintf("- **%d pull requests across %d repositories, %d review verdicts recorded** — the evidence this is measured from, %s.", r.PRs, len(r.Repos), r.Verdicts, asOf))
	add("")
	add(fmt.Sprintf("How measured: per-PR evidence bundles the spoke already writes, folded per PR; 95%% Wilson intervals; n < %d is never reported. Full tables, trend and methodology in [%s](%s).", MinN, report, report))
	add("")
	add(fmt.Sprintf("![mediated vs unmediated](%s/assets/%s-bars.svg)", docDir, r.AssetBase()))
	add(fmt.Sprintf("![trend by month](%s/assets/%s-trend.svg)", docDir, r.AssetBase()))
	add(ReadmeEnd)
	return strings.Join(lines, "\n")
}

// UpdateReadme replaces the marker block in readme with block. The block is
// expected to start with ReadmeStart and end with ReadmeEnd.
func UpdateReadme(readme, block string) (string, error) {
	start := strings.Index(readme, ReadmeStart)
	end := strings.Index(readme, ReadmeEnd)
	if start < 0 || end < start {
		return "", ErrNoMarkers
	}
	return readme[:start] + block + readme[end+len(ReadmeEnd):], nil
}

// ExtractReadmeBlock returns the current marker block, markers included.
func ExtractReadmeBlock(readme string) (string, error) {
	start := strings.Index(readme, ReadmeStart)
	end := strings.Index(readme, ReadmeEnd)
	if start < 0 || end < start {
		return "", ErrNoMarkers
	}
	return readme[start : end+len(ReadmeEnd)], nil
}
