package outcomebench

import (
	"errors"
	"fmt"
	"strings"
)

// README markers; everything between them is owned by the generator.
const (
	ReadmeStart = "<!-- outcomes:start -->"
	ReadmeEnd   = "<!-- outcomes:end -->"
)

// ErrNoMarkers is returned when a README has no outcomes block to rewrite.
var ErrNoMarkers = errors.New("README has no " + ReadmeStart + " … " + ReadmeEnd + " block")

// ReadmeBlock renders the README evidence section for a general reader:
// one line of scale, then Accuracy / Security / Cost / Also, each a card
// (a <picture> with a dark and a light SVG) and at most two flat sentences,
// one of which states the limit of the number. No statistical vocabulary
// appears here; it lives in the report. docDir is the path from the README
// to the benchmark directory.
func (r Report) ReadmeBlock(docDir string) string {
	report := fmt.Sprintf("%s/outcomes-%s.md", docDir, r.Month())
	var lines []string
	add := func(s ...string) { lines = append(lines, s...) }
	cards := func(width int, names ...string) {
		var shown []string
		for _, n := range names {
			if r.HasCard(n) {
				shown = append(shown, r.picture(docDir, n, width))
			}
		}
		if len(shown) > 0 {
			add(`<p align="center">`)
			add(shown...)
			add("</p>", "")
		}
	}
	add(ReadmeStart)
	add(fmt.Sprintf("<!-- generated by src/scripts/outcome-benchmark.sh --readme; do not edit by hand. Report: %s -->", report))
	add(r.HeroLine(), "")

	add("## Accuracy", "")
	if r.HasCard(CardCameBack) || r.HasCard(CardStories) {
		add("A separate reviewer reads every pull request an agent opens and can send it back before it merges. The question is whether its objections hold up.", "")
		cards(cardW, CardCameBack, CardTimeToApproval)
		cards(cardWideW, CardStories)
		add(r.followupCaveat(), "")
	} else {
		add("Not enough reviewed pull requests are on record yet to report accuracy figures.", "")
	}

	add("## Security", "")
	add("Agents work with short-lived, task-scoped access; pull requests from untrusted authors are held for a human; every merge is signed off and credits the issue author.", "")
	cards(cardW, CardPromptInjection)

	add("## Cost", "")
	if r.HasCard(CardCost) {
		add("Each agent card in the dashboard shows what the current task has cost so far. The figure below is an estimate from provider pricing; some models are unpriced.", "")
		cards(cardW, CardCost)
	} else {
		add("Cost per merged pull request is reported once enough hive-attributed merges are on record.", "")
	}

	add("## Also", "")
	cards(cardWideW, CardAlso)

	add(fmt.Sprintf("Production data, not a lab run. Every count above is regenerated from live records by `src/scripts/outcome-benchmark.sh`; bases, dates, exclusions and the full tables are in [how we count →](%s).", report))
	add(ReadmeEnd)
	return strings.Join(lines, "\n")
}

// followupCaveat is the one honest sentence under the Accuracy cards: what
// happened to the rest, and why shipped-code outcomes are not shown yet.
func (r Report) followupCaveat() string {
	f := r.Followup
	var parts []string
	if f.MergedSameHead > 0 {
		parts = append(parts, fmt.Sprintf("%s of the sent-back pull requests merged unchanged, %s of them after another review pass approved the same version", commas(f.MergedSameHead), commas(f.MergedSameHeadApproved)))
	}
	if f.Unresolved > 0 {
		parts = append(parts, fmt.Sprintf("%s did not merge", commas(f.Unresolved)))
	}
	s := ""
	if len(parts) > 0 {
		s = strings.Join(parts, "; ") + ". "
	}
	return s + fmt.Sprintf("Whether reviewed code later had to be reverted needs merges at least %d days old; reviewed merges only began %s, so those figures are in the report, not here.", int(Maturation.Hours()/24), monthLabel(r.FirstMediatedMerge))
}

// HeroLine is the one sentence of scale at the top of the README.
func (r Report) HeroLine() string {
	s := fmt.Sprintf("Measured on %s pull requests across %d repositories", commas(r.PRs), len(r.Repos))
	if r.Verdicts > 0 {
		s += fmt.Sprintf(" and %s review verdicts", commas(r.Verdicts))
	}
	return s + fmt.Sprintf(", as of %s.", day(r.GeneratedAt))
}

// picture is the GitHub-flavoured <picture> that swaps the card SVG with
// the reader's colour scheme; the alt text is the card's title sentence.
func (r Report) picture(docDir, card string, width int) string {
	alt := card
	if svg, ok := r.Card(card, cardThemes[0]); ok {
		if i, j := strings.Index(svg, "<title>"), strings.Index(svg, "</title>"); i >= 0 && j > i {
			alt = svg[i+len("<title>") : j]
		}
	}
	return fmt.Sprintf(`<picture><source media="(prefers-color-scheme: dark)" srcset="%s/assets/%s"><img alt="%s" width="%d" src="%s/assets/%s"></picture>`,
		docDir, r.CardFile(card, "dark"), alt, width, docDir, r.CardFile(card, "light"))
}

// HowItWorksPicture is the ladder card for the README's own section.
func (r Report) HowItWorksPicture(docDir string) string {
	return r.picture(docDir, CardHowItWorks, cardWideW)
}

// UpdateReadme replaces the marker block in readme with block. The block is
// expected to start with ReadmeStart and end with ReadmeEnd.
func UpdateReadme(readme, block string) (string, error) {
	start := strings.Index(readme, ReadmeStart)
	end := strings.Index(readme, ReadmeEnd)
	if start < 0 || end < start {
		return "", ErrNoMarkers
	}
	return readme[:start] + block + readme[end+len(ReadmeEnd):], nil
}

// ExtractReadmeBlock returns the current marker block, markers included.
func ExtractReadmeBlock(readme string) (string, error) {
	start := strings.Index(readme, ReadmeStart)
	end := strings.Index(readme, ReadmeEnd)
	if start < 0 || end < start {
		return "", ErrNoMarkers
	}
	return readme[start : end+len(ReadmeEnd)], nil
}
