package outcomebench

import (
	"fmt"
	"strings"
	"time"
)

// NotReported is the text of a cell whose sample is below MinN.
const NotReported = "not reported"

// FormatRate renders a rate as "12.3% (95% CI 8.1–17.9%; 12/97)", or
// "not reported (n=4)" when N is below MinN.
func FormatRate(r Rate) string {
	if !r.Reported() {
		return fmt.Sprintf("%s (n=%d)", NotReported, r.N)
	}
	lo, hi := r.Interval()
	return fmt.Sprintf("%.1f%% (95%% CI %.1f–%.1f%%; %d/%d)", 100*r.Value(), 100*lo, 100*hi, r.K, r.N)
}

// FormatMedian renders a median time to merge in hours, or "not reported"
// when N is below MinN.
func FormatMedian(m Median) string {
	if !m.Reported() {
		return fmt.Sprintf("%s (n=%d)", NotReported, m.N)
	}
	return fmt.Sprintf("%.1fh (n=%d)", m.D.Hours(), m.N)
}

func formatBound(t time.Time, open string) string {
	if t.IsZero() {
		return open
	}
	return t.UTC().Format(time.RFC3339)
}

func population(s CohortStats) string {
	return fmt.Sprintf("%d (%d merged · %d closed · %d open · %d unknown)", s.PRs, s.Merged, s.Closed, s.Open, s.Unknown)
}

// table renders the metric rows for the given columns. mediatedOnly marks
// columns whose changes-requested cell is n/a by definition.
func table(b *strings.Builder, cols []CohortStats, mediatedOnly []bool, cost []string) {
	b.WriteString("| Metric |")
	for _, c := range cols {
		fmt.Fprintf(b, " %s |", c.Label)
	}
	b.WriteString("\n|---|")
	for range cols {
		b.WriteString("---|")
	}
	b.WriteString("\n")
	row := func(name string, cell func(i int, c CohortStats) string) {
		fmt.Fprintf(b, "| %s |", name)
		for i, c := range cols {
			fmt.Fprintf(b, " %s |", cell(i, c))
		}
		b.WriteString("\n")
	}
	row("PRs in window", func(_ int, c CohortStats) string { return population(c) })
	row("Revert rate (merged PRs)", func(_ int, c CohortStats) string { return FormatRate(c.Revert) })
	row("Change-failure rate (reverts + issue reopens, merged PRs)", func(_ int, c CohortStats) string { return FormatRate(c.ChangeFailure) })
	row("CI failure at merged head", func(_ int, c CohortStats) string { return FormatRate(c.CIFailure) })
	row("Hive `changes_requested` verdict rate (mediated PRs)", func(i int, c CohortStats) string {
		if mediatedOnly[i] {
			return "n/a (no Hive verdicts by definition)"
		}
		return FormatRate(c.ChangesRequested)
	})
	row("Median time to merge", func(_ int, c CohortStats) string { return FormatMedian(c.TimeToMerge) })
	if cost != nil {
		row("Cost per merged PR", func(i int, _ CohortStats) string { return cost[i] })
	}
}

// Render returns the report as Markdown: header, headline table, the
// control-window cut when present, what schema v1 cannot answer, and the
// methodology. The output depends only on the report, so the same evidence
// and options always render the same bytes.
func Render(r Report) string {
	var b strings.Builder
	o := r.Options
	b.WriteString("# Outcome benchmark: Hive-mediated vs unmediated pull requests\n\n")
	b.WriteString("<!-- Generated by `hivectl evidence benchmark`; regenerate, do not edit by hand. -->\n\n")
	root := o.Root
	if root == "" {
		root = "(not recorded)"
	}
	repo := o.Repo
	if repo == "" {
		repo = "all repositories"
	}
	fmt.Fprintf(&b, "- **Evidence root:** `%s` (schema %s bundles)\n", root, "v1")
	fmt.Fprintf(&b, "- **Repository:** %s\n", repo)
	fmt.Fprintf(&b, "- **Window:** PRs opened from %s to %s (exclusive)\n",
		formatBound(o.Since, "the first record"), formatBound(o.Until, "the last record"))
	fmt.Fprintf(&b, "- **PRs in window:** %d (%d mediated, %d unmediated; %d backfilled from forge history)\n",
		r.PRs, r.Mediated.PRs, r.Unmediated.PRs, r.Mediated.Backfilled+r.Unmediated.Backfilled)
	fmt.Fprintf(&b, "- **Files skipped as unreadable or not schema v1:** %d\n", r.Unreadable)
	fmt.Fprintf(&b, "- **Minimum n per cell:** %d (smaller cells read `%s`)\n\n", MinN, NotReported)

	b.WriteString("## Headline\n\n")
	cost := []string{"", "n/a (no Hive spend by definition)"}
	switch usd, ok, reported := r.CostPerMergedPR(); {
	case !ok:
		cost[0] = "not available (no fleet spend supplied)"
	case !reported:
		cost[0] = fmt.Sprintf("%s (n=%d)", NotReported, r.Mediated.MergedMediated)
	default:
		cost[0] = fmt.Sprintf("$%.2f ($%.2f ÷ %d merged mediated PRs)", usd, *o.FleetSpendUSD, r.Mediated.MergedMediated)
	}
	table(&b, []CohortStats{r.Mediated, r.Unmediated}, []bool{false, true}, cost)

	b.WriteString("\n## Secondary cut: control window\n\n")
	if r.HasControlWindow {
		b.WriteString("PRs carrying a prospective `control_window` assignment, mediated and unmediated together. PRs without an assignment (or with conflicting ones across heads) are in neither column.\n\n")
		table(&b, []CohortStats{r.ControlOn, r.ControlOff}, []bool{false, false}, nil)
	} else {
		b.WriteString("No PR in the window carries a `control_window` assignment, so this cut is omitted.\n")
	}

	b.WriteString("\n## Not available in evidence schema v1\n\n")
	b.WriteString("These are listed rather than approximated; adding them needs new telemetry, which this report does not introduce.\n\n")
	b.WriteString("- **Post-merge CI re-runs:** a bundle captures CI at the reviewed head only; later runs on the base branch are not recorded.\n")
	b.WriteString("- **Human `changes_requested` reviews:** `human_actions` records approvals, labels and hold lifts, not human review verdicts, so a human changes-requested rate cannot be computed for either cohort.\n")
	if o.FleetSpendUSD == nil {
		b.WriteString("- **Cost per merged PR:** spend is not part of a bundle; supply the fleet's estimated spend for the window (`--fleet-spend-usd`) to report it.\n")
	}

	b.WriteString("\n## Methodology\n\n")
	b.WriteString("- **Population.** Every schema v1 bundle under the evidence root is folded per PR with `evidence.FoldPRs`, the same fold `GET /api/evidence/summary` and `hivectl evidence export` use, and a PR is placed in the window by its open time (earliest `created_at` or `merge.opened_at`), never by when a bundle was written. Nothing is excluded silently: backfilled PRs are counted (and flagged above), files that do not parse are counted as skipped.\n")
	b.WriteString("- **Cohorts.** A PR is *mediated* when at least one of its records carries a Hive reviewer verdict (`verdicts[]`) or a review Hive posted (`posted_reviews[]`); otherwise it is *unmediated*. Backfilled bundles never carry verdicts, so PRs known only from forge history are unmediated. This is an observational split, not a randomised one: the two cohorts can differ in author, repository and size, and differences between them are not causal estimates. The `control_window` cut, when present, is the prospectively assigned arm.\n")
	b.WriteString("- **Outcome.** Merged when any record holds a merge event; closed when a backfilled or forge-observed outcome says closed without merge; open when an outcome is known and neither; unknown when no record says (a live bundle for a PR this hive did not merge). Rates over merged PRs leave open, closed and unknown PRs out of the denominator.\n")
	b.WriteString("- **Revert rate.** Merged PRs with a `reverted_by` link (a revert merged within the link window) ÷ merged PRs.\n")
	b.WriteString("- **Change-failure rate.** Hive's existing definition (`evidence.PR.ChangeFailure`): merged PRs reverted, or whose closed issue a person reopened within the link window of the merge, ÷ merged PRs.\n")
	b.WriteString("- **CI failure at merged head.** Among merged PRs whose merged-head bundle captured a CI verdict (`ci.status` success or failure; pending and missing are left out), the share that was failure. The merged-head bundle is the record whose `head_sha` matches `merge.sha`, else the PR's newest record.\n")
	b.WriteString("- **Hive `changes_requested` verdict rate.** Mediated PRs with at least one `changes_requested` reviewer verdict on any head ÷ mediated PRs. Unmediated PRs have no Hive verdicts by definition.\n")
	b.WriteString("- **Median time to merge.** `merge.at − merge.opened_at` over merged PRs that captured `opened_at` (`evidence.MedianTimeToMerge`; an even count takes the mean of the middle two). PRs without it are skipped, never counted as zero; n is the measurable count.\n")
	b.WriteString("- **Cost per merged PR.** Optional input: the fleet's estimated spend over the window ÷ merged mediated PRs.\n")
	fmt.Fprintf(&b, "- **Intervals and suppression.** Rates carry 95%% Wilson score intervals (z = 1.96, the formula in `pkg/hub/evidence.go`). Any cell with n < %d reads `%s` with its n; no claim is made without n.\n", MinN, NotReported)
	b.WriteString("- **Reproducibility.** The report is a pure function of the bundles and the flags (no wall clock, ordered output), so re-running `src/scripts/outcome-benchmark.sh` with the same month on the same evidence root reproduces the same table byte for byte.\n")
	return b.String()
}
