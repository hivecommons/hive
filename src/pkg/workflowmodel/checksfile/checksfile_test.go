// fakeRepo is an in-memory repository: branches map to file trees, and at
// most one PR is tracked for the checks branch.
type fakeRepo struct {
	branches   map[string]map[string]string
	heads      map[string]string
	openPR     int
	commits    []string
	createdPRs []string
	readErr    error
}

func newFakeRepo() *fakeRepo {
	return &fakeRepo{
		branches: map[string]map[string]string{"main": {}},
		heads:    map[string]string{"main": "base-0"},
	}
}

func notFound() error {
	return fmt.Errorf("getting file: %w", &gh.ErrorResponse{Response: &http.Response{StatusCode: http.StatusNotFound}})
}

func (f *fakeRepo) DefaultBranch(context.Context, string, string) (string, error) { return "main", nil }

func (f *fakeRepo) OpenPRForHead(_ context.Context, repo, branch string) (int, string, bool, error) {
	if f.openPR == 0 || branch != Branch {
		return 0, "", false, nil
	}
	return f.openPR, "", true, nil
}

func (f *fakeRepo) GetFileContentRef(_ context.Context, _, _, path, ref string) (string, error) {
	if f.readErr != nil {
		return "", f.readErr
	}
	content, ok := f.branches[ref][path]
	if !ok {
		return "", notFound()
	}
	return content, nil
}

func (f *fakeRepo) LatestCommitHash(_ context.Context, _, _, branch string) (string, error) {
	return f.heads[branch], nil
}

func (f *fakeRepo) ResetBranch(_ context.Context, _, branch, base string) (string, error) {
	if branch == base {
		return "", errors.New("reset onto base")
	}
	tree := map[string]string{}
	for k, v := range f.branches[base] {
		tree[k] = v
	}
	f.branches[branch] = tree
	f.heads[branch] = f.heads[base]
	return f.heads[base], nil
}

func (f *fakeRepo) CommitFilesOnBranch(_ context.Context, _, branch, expected, headline, _ string, files map[string]string) (string, error) {
	if branch != Branch {
		return "", fmt.Errorf("commit to %s: only the checks branch may be written", branch)
	}
	if f.heads[branch] != expected {
		return "", fmt.Errorf("expected head %s, branch is at %s", expected, f.heads[branch])
	}
	for k, v := range files {
		f.branches[branch][k] = v
	}
	f.commits = append(f.commits, headline)
	f.heads[branch] = fmt.Sprintf("commit-%d", len(f.commits))
	return f.heads[branch], nil
}

func (f *fakeRepo) CreatePR(_ context.Context, repo, head, base, title, _ string) (hgithub.CreatePRResult, error) {
	f.openPR = 7
	f.createdPRs = append(f.createdPRs, repo+" "+head+"->"+base+" "+title)
	return hgithub.CreatePRResult{Number: f.openPR}, nil
}

func modelWithChecks(checks ...workflowmodel.Check) *workflowmodel.Model {
	m := &workflowmodel.Model{APIVersion: workflowmodel.APIVersion, Metadata: workflowmodel.Metadata{Name: "acme-flow"}}
	m.Spec.Meta.Version = "2"
	m.Spec.Checks = checks
	return m
}

func TestRenderDeclaredChecks(t *testing.T) {
	m := modelWithChecks(
		workflowmodel.Check{ID: "check-build", Name: "build", Kind: workflowmodel.CheckCI, Required: true, Source: "/repos/acme/app/branches/main/protection"},
		workflowmodel.Check{ID: "pr-template-tests", Name: "Tests added", Kind: workflowmodel.CheckManual, Source: ".github/PULL_REQUEST_TEMPLATE.md:4"},
	)
	out, ok, err := Render(m)
	if err != nil || !ok {
		t.Fatalf("Render: ok=%v err=%v", ok, err)
	}
	if !strings.HasPrefix(out, "# Generated by Hive") {
		t.Fatalf("missing header:\n%s", out)
	}
	var doc document
	if err := yaml.Unmarshal([]byte(out), &doc); err != nil {
		t.Fatalf("rendered file is not YAML: %v\n%s", err, out)
	}
	if doc.APIVersion != workflowmodel.APIVersion || doc.Kind != Kind || doc.Model != (modelID{Name: "acme-flow", Version: "2"}) {
		t.Fatalf("header fields: %+v", doc)
	}
	if len(doc.Checks) != 2 || doc.Checks[0] != (check{ID: "check-build", Name: "build", Kind: "ci", Required: true, Source: "/repos/acme/app/branches/main/protection"}) || doc.Checks[1].ID != "pr-template-tests" || doc.Checks[1].Required {
		t.Fatalf("checks: %+v", doc.Checks)
	}
	again, _, _ := Render(m)
	if again != out {
		t.Fatal("Render is not deterministic")
	}
	if _, ok, _ := Render(modelWithChecks()); ok {
		t.Fatal("a model without checks must render nothing")
	}
}

func TestEmitOpensPRThenSkipsWhenUpToDate(t *testing.T) {
	ctx := context.Background()
	f := newFakeRepo()
	m := modelWithChecks(workflowmodel.Check{ID: "check-build", Name: "build", Kind: workflowmodel.CheckCI, Required: true})

	res, err := Emit(ctx, f, "acme/app", "", m)
	if err != nil || res.Outcome != OpenedPR || res.PR != 7 {
		t.Fatalf("first emit: %+v %v", res, err)
	}
	if len(f.createdPRs) != 1 || f.createdPRs[0] != "acme/app "+Branch+"->main 🌱 workflow: checks from acme-flow@2" {
		t.Fatalf("PRs: %q", f.createdPRs)
	}
	if _, onBase := f.branches["main"][Path]; onBase {
		t.Fatal("the base branch must never be written")
	}
	want, _, _ := Render(m)
	if f.branches[Branch][Path] != want {
		t.Fatalf("committed file:\n%s", f.branches[Branch][Path])
	}

	res, err = Emit(ctx, f, "acme/app", "", m)
	if err != nil || res.Outcome != UpToDate || len(f.commits) != 1 || len(f.createdPRs) != 1 {
		t.Fatalf("unchanged emit: %+v %v commits=%d prs=%d", res, err, len(f.commits), len(f.createdPRs))
	}

	m.Spec.Checks = append(m.Spec.Checks, workflowmodel.Check{ID: "check-lint", Name: "lint", Kind: workflowmodel.CheckCI})
	res, err = Emit(ctx, f, "acme/app", "", m)
	if err != nil || res.Outcome != UpdatedPR || res.PR != 7 || len(f.commits) != 2 || len(f.createdPRs) != 1 {
		t.Fatalf("changed emit: %+v %v commits=%d prs=%d", res, err, len(f.commits), len(f.createdPRs))
	}
	if !strings.Contains(f.branches[Branch][Path], "check-lint") {
		t.Fatalf("update not committed:\n%s", f.branches[Branch][Path])
	}
}

func TestEmitSkipsWhenBaseAlreadyMatches(t *testing.T) {
	f := newFakeRepo()
	m := modelWithChecks(workflowmodel.Check{ID: "check-build", Name: "build"})
	content, _, _ := Render(m)
	f.branches["main"][Path] = content
	res, err := Emit(context.Background(), f, "acme/app", "", m)
	if err != nil || res.Outcome != UpToDate || len(f.commits) != 0 || len(f.createdPRs) != 0 {
		t.Fatalf("%+v %v commits=%d prs=%d", res, err, len(f.commits), len(f.createdPRs))
	}
}

func TestEmitWithoutChecksTouchesNothing(t *testing.T) {
	f := newFakeRepo()
	f.readErr = errors.New("must not read")
	res, err := Emit(context.Background(), f, "acme/app", "", modelWithChecks())
	if err != nil || res.Outcome != NoChecks {
		t.Fatalf("%+v %v", res, err)
	}
}

func TestEmitRejectsBadInput(t *testing.T) {
	m := modelWithChecks(workflowmodel.Check{ID: "c", Name: "c"})
	if _, err := Emit(context.Background(), nil, "acme/app", "", m); !errors.Is(err, hgithub.ErrNoGitHubClient) {
		t.Fatalf("nil client: %v", err)
	}
	if _, err := Emit(context.Background(), newFakeRepo(), "app", "", m); err == nil {
		t.Fatal("bare repository name accepted")
	}
	if _, err := Emit(context.Background(), newFakeRepo(), "acme/app", Branch, m); err == nil {
		t.Fatal("checks branch accepted as base")
	}
	f := newFakeRepo()
	f.readErr = errors.New("boom")
	if _, err := Emit(context.Background(), f, "acme/app", "", m); err == nil || len(f.commits) != 0 {
		t.Fatalf("read error: %v commits=%d", err, len(f.commits))
	}
}
