// Package checksfile emits a bound workflow model's declared checks to the
// repository as .hive/workflows/checks.yml (hivecommons/hive#18355, a
// follow-up to #17620).
//
// The file is only ever proposed: it travels on one hive-owned branch as a
// GitHub-signed commit and lands through a normal pull request, never a
// direct push to the base branch. A model that declares no checks emits
// nothing, and a file that already matches the rendered content (on the
// open PR's branch, or on the base branch when no PR is open) is left alone,
// so re-binding the same model is a no-op.
package checksfile

import (
	"bytes"
	"context"
	"errors"
	"fmt"
	"net/http"
	"strings"

	gh "github.com/google/go-github/v72/github"
	"gopkg.in/yaml.v3"

	hgithub "github.com/hivecommons/hive/pkg/github"
	"github.com/hivecommons/hive/pkg/workflowmodel"
)

// Path is the repository path the checks file is written to.
const Path = ".hive/workflows/checks.yml"

// Branch is the fixed head branch of the checks PR. Every emit commits to
// it, so one open PR accumulates updates instead of a new PR per change.
const Branch = "hive/workflow-checks"

// Kind is the document kind of the emitted file.
const Kind = "WorkflowChecks"

// RepoClient is the GitHub surface the emitter needs. *github.Client
// satisfies it, and it is the same surface as knowledge.BeadSynthRepoClient.
type RepoClient interface {
	DefaultBranch(ctx context.Context, owner, repo string) (string, error)
	OpenPRForHead(ctx context.Context, repo, branch string) (number int, url string, ok bool, err error)
	GetFileContentRef(ctx context.Context, owner, repo, path, ref string) (string, error)
	LatestCommitHash(ctx context.Context, owner, repo, branch string) (string, error)
	ResetBranch(ctx context.Context, repo, branch, base string) (string, error)
	CommitFilesOnBranch(ctx context.Context, repo, branch, expectedHeadSHA, headline, body string, files map[string]string) (string, error)
	CreatePR(ctx context.Context, repo, head, base, title, body string) (hgithub.CreatePRResult, error)
}

// Outcome says what Emit did.
type Outcome string

// Outcomes.
const (
	// NoChecks: the model declares no checks; nothing was read or written.
	NoChecks Outcome = "no-checks"
	// UpToDate: the file already matches; no commit or PR was made.
	UpToDate Outcome = "up-to-date"
	// UpdatedPR: the file was committed to the already-open checks PR.
	UpdatedPR Outcome = "updated-pr"
	// OpenedPR: the file was committed and a new checks PR opened.
	OpenedPR Outcome = "opened-pr"
)

// Result reports one Emit.
type Result struct {
	Outcome Outcome `json:"outcome"`
	PR      int     `json:"pr,omitempty"`
}

type document struct {
	APIVersion string  `yaml:"apiVersion"`
	Kind       string  `yaml:"kind"`
	Model      modelID `yaml:"model"`
	Checks     []check `yaml:"checks"`
}

type modelID struct {
	Name    string `yaml:"name"`
	Version string `yaml:"version,omitempty"`
}

type check struct {
	ID       string `yaml:"id"`
	Name     string `yaml:"name"`
	Kind     string `yaml:"kind,omitempty"`
	Required bool   `yaml:"required,omitempty"`
	Source   string `yaml:"source,omitempty"`
}

const header = "# Generated by Hive from the repository's bound workflow model.\n" +
	"# Edits here are overwritten; change the model instead.\n"

// Render returns the checks file for m in declaration order, or ok=false
// when m declares no checks. It carries only the model's name, version and
// checks, so an unrelated model change renders identically.
func Render(m *workflowmodel.Model) (content string, ok bool, err error) {
	if m == nil || len(m.Spec.Checks) == 0 {
		return "", false, nil
	}
	doc := document{
		APIVersion: workflowmodel.APIVersion,
		Kind:       Kind,
		Model:      modelID{Name: m.Metadata.Name, Version: m.Spec.Meta.Version},
		Checks:     make([]check, 0, len(m.Spec.Checks)),
	}
	for _, c := range m.Spec.Checks {
		doc.Checks = append(doc.Checks, check{ID: c.ID, Name: c.Name, Kind: string(c.Kind), Required: c.Required, Source: c.Source})
	}
	var buf bytes.Buffer
	buf.WriteString(header)
	enc := yaml.NewEncoder(&buf)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return "", false, fmt.Errorf("rendering %s: %w", Path, err)
	}
	if err := enc.Close(); err != nil {
		return "", false, fmt.Errorf("rendering %s: %w", Path, err)
	}
	return buf.String(), true, nil
}

// Emit proposes m's checks file to repo ("owner/name") through the checks
// PR. base selects the PR's base branch; empty means the repository's
// default branch.
func Emit(ctx context.Context, client RepoClient, repo, base string, m *workflowmodel.Model) (Result, error) {
	if client == nil {
		return Result{}, hgithub.ErrNoGitHubClient
	}
	content, ok, err := Render(m)
	if err != nil {
		return Result{}, err
	}
	if !ok {
		return Result{Outcome: NoChecks}, nil
	}
	owner, name, found := strings.Cut(strings.TrimSpace(repo), "/")
	if !found || owner == "" || name == "" || strings.Contains(name, "/") {
		return Result{}, fmt.Errorf("repository %q is not owner/name", repo)
	}
	fullRepo := owner + "/" + name
	base = strings.TrimSpace(base)
	if base == "" {
		if base, err = client.DefaultBranch(ctx, owner, name); err != nil {
			return Result{}, fmt.Errorf("resolving default branch of %s: %w", fullRepo, err)
		}
	}
	if base == Branch {
		return Result{}, fmt.Errorf("base branch of %s must differ from %s", fullRepo, Branch)
	}
	prNumber, _, open, err := client.OpenPRForHead(ctx, fullRepo, Branch)
	if err != nil {
		return Result{}, err
	}
	ref := base
	if open {
		ref = Branch
	}
	current, err := client.GetFileContentRef(ctx, owner, name, Path, ref)
	switch {
	case err == nil && current == content:
		return Result{Outcome: UpToDate, PR: prNumber}, nil
	case err != nil && !isNotFound(err):
		return Result{}, fmt.Errorf("reading %s at %s: %w", Path, ref, err)
	}

	var head string
	if open {
		head, err = client.LatestCommitHash(ctx, owner, name, Branch)
	} else {
		head, err = client.ResetBranch(ctx, fullRepo, Branch, base)
	}
	if err != nil {
		return Result{}, err
	}
	model := modelKey(m)
	headline := "chore(workflow): update " + Path + " from " + model
	if _, err := client.CommitFilesOnBranch(ctx, fullRepo, Branch, head, headline, "", map[string]string{Path: content}); err != nil {
		return Result{}, err
	}
	if open {
		return Result{Outcome: UpdatedPR, PR: prNumber}, nil
	}
	res, err := client.CreatePR(ctx, fullRepo, Branch, base, "🌱 workflow: checks from "+model, prBody(model, len(m.Spec.Checks)))
	if err != nil {
		return Result{}, err
	}
	return Result{Outcome: OpenedPR, PR: res.Number}, nil
}

func modelKey(m *workflowmodel.Model) string {
	if v := strings.TrimSpace(m.Spec.Meta.Version); v != "" {
		return m.Metadata.Name + "@" + v
	}
	return m.Metadata.Name
}

func prBody(model string, n int) string {
	return fmt.Sprintf("This repository is bound to the Hive workflow model `%s`, which declares %d check(s). "+
		"This PR records them in `%s` so the checks the workflow gates on are reviewable in the repository. "+
		"Later changes to the model update this PR in place; nothing lands until it is merged.\n", model, n, Path)
}

func isNotFound(err error) bool {
	var ghErr *gh.ErrorResponse
	return errors.As(err, &ghErr) && ghErr.Response != nil && ghErr.Response.StatusCode == http.StatusNotFound
}
