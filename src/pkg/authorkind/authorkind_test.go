func TestExplainRulesInOrder(t *testing.T) {
	cases := []struct {
		name string
		in   Input
		kind Kind
		rule string
	}{
		{"app login", Input{Author: "app/acme-hive[bot]", AppLogin: "app/acme-hive", Body: appBody}, Hive, RuleAppLogin},
		{"app login case and suffix", Input{Author: "App/Acme-Hive", AppLogin: "app/acme-hive[bot]"}, Hive, RuleAppLogin},
		{"agent label without app login", Input{Author: "someone", Labels: []string{"size/M", "agent/scanner"}, Body: appBody}, Hive, RuleAgentLabel},
		{"origin marker local", Input{Author: "mendezr", HiveID: "acme hive", Body: "x\n<!-- hive:origin hive=acme-hive at=2026-10-16T00:00:00Z -->"}, Hive, RuleOriginLocal},
		{"origin marker foreign", Input{Author: "mendezr", HiveID: "acme-hive", Body: "x\n<!-- hive:origin hive=mendezr-hive -->"}, Clanker, RuleOriginForeign},
		{"origin marker no local id", Input{Author: "mendezr", Body: "<!-- hive:origin hive=mendezr-hive -->"}, Clanker, RuleOriginForeign},
		{"attribution trailer", Input{Author: "mendezr", AppLogin: "app/acme-hive", Body: relayBody}, Clanker, RuleAttributionTrailer},
		{"identity footer only", Input{Author: "karibhou", Body: "---\n🐝 **Hive Agent**: `contributor` | **SHA:** `abc`"}, Clanker, RuleIdentityFooter},
		{"registry fallback", Input{Author: "mendezr", Body: "plain body", RelayKnown: true}, Clanker, RuleRegistry},
		{"workflow run of this repo under a user PAT", Input{Author: "clubanderson", AppLogin: "app/acme-hive", PRURL: "https://GitHub.com/HiveCommons/Hive/pull/17354", Body: workflowBody}, Clanker, RuleWorkflowRun},
		{"workflow run beats registry", Input{Author: "clubanderson", PRURL: "https://github.com/hivecommons/hive/pull/17354", Body: workflowBody, RelayKnown: true}, Clanker, RuleWorkflowRun},
		{"workflow run of another repo is human", Input{Author: "clubanderson", PRURL: "https://github.com/acme/widgets/pull/1", Body: workflowBody}, Human, RuleDefaultHuman},
		{"workflow run on another server is human", Input{Author: "clubanderson", PRURL: "https://github.com/hivecommons/hive/pull/17354", Body: "Generated by [price-table-refresh](https://example.invalid/hivecommons/hive/actions/runs/1)"}, Human, RuleDefaultHuman},
		{"workflow run without repo is human", Input{Author: "clubanderson", Body: workflowBody}, Human, RuleDefaultHuman},
		{"bare run link is human", Input{Author: "clubanderson", PRURL: "https://github.com/hivecommons/hive/pull/17354", Body: "CI failed: https://github.com/hivecommons/hive/actions/runs/1"}, Human, RuleDefaultHuman},
		{"foreign bot", Input{Author: "dependabot[bot]", AppLogin: "app/acme-hive", Body: "Bumps x"}, Unknown, RuleBot},
		{"human", Input{Author: "clubanderson", AppLogin: "app/acme-hive", Body: "Fixes the thing.\n\nSigned-off-by: me"}, Human, RuleDefaultHuman},
		{"empty", Input{}, Human, RuleDefaultHuman},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			kind, rule := Explain(tc.in)
			if kind != tc.kind || rule != tc.rule {
				t.Fatalf("Explain = (%q, %s) want (%q, %s)", kind, rule, tc.kind, tc.rule)
			}
			if Detect(tc.in) != tc.kind {
				t.Fatalf("Detect disagrees with Explain")
			}
		})
	}
}

// An already-applied author/* label never decides Detect: it is the
// engine's output and a stale one must not stick.
func TestDetectIgnoresExistingKindLabels(t *testing.T) {
	in := Input{Author: "clubanderson", Labels: []string{"author/hive", "author/clanker"}, Body: "hand written"}
	if got := Detect(in); got != Human {
		t.Fatalf("Detect = %q want human", got)
	}
	if got := FromLabels(in.Labels, Names{}); got != Hive {
		t.Fatalf("FromLabels = %q want hive (hive outranks clanker)", got)
	}
}

func TestNamesAndLabels(t *testing.T) {
	n := Names{Clanker: " author/relay "}.Normalize()
	want := Names{Human: "author/human", Clanker: "author/relay", Hive: "author/hive"}
	if n != want {
		t.Fatalf("Normalize = %+v", n)
	}
	if n.Label(Clanker) != "author/relay" || n.Label(Unknown) != "" || Hive.Label() != "author/hive" {
		t.Fatal("Label rendering")
	}
	if !reflect.DeepEqual(n.All(), []string{"author/human", "author/relay", "author/hive"}) {
		t.Fatalf("All = %v", n.All())
	}
	if FromLabels([]string{"author/relay"}, n) != Clanker || FromLabels([]string{"author/clanker"}, n) != Unknown {
		t.Fatal("FromLabels must use the configured names")
	}
	if Human.String() != "human" || Unknown.String() != "" {
		t.Fatal("String")
	}
}

// GitLab and Gitea PRs carry the same markers and trailer (relayed bodies are
// forge-neutral text), but their bot accounts do not use GitHub's `[bot]`
// suffix: each forge's own convention must read as a bot there, and only there.
func TestExplainForgeAware(t *testing.T) {
	cases := []struct {
		name string
		in   Input
		kind Kind
		rule string
	}{
		{"gitlab trailer", Input{Forge: "gitlab", Author: "mendezr", AppLogin: "project_42_bot_a1b2c3", Body: relayBody}, Clanker, RuleAttributionTrailer},
		{"gitea trailer", Input{Forge: "gitea", Author: "mendezr", AppLogin: "acme-hive", Body: relayBody}, Clanker, RuleAttributionTrailer},
		{"gitlab hive token user is the app", Input{Forge: "gitlab", Author: "project_42_bot_a1b2c3", AppLogin: "project_42_bot_a1b2c3", Body: appBody}, Hive, RuleAppLogin},
		{"gitlab origin local", Input{Forge: "gitlab", Author: "mendezr", HiveID: "acme-hive", Body: "<!-- hive:origin hive=acme-hive -->"}, Hive, RuleOriginLocal},
		{"gitlab project bot", Input{Forge: "gitlab", Author: "project_7_bot_9f8e", AppLogin: "project_42_bot_a1b2c3", Body: "Bumps x"}, Unknown, RuleBot},
		{"gitlab group bot", Input{Forge: "gitlab", Author: "group_3_bot", Body: "Bumps x"}, Unknown, RuleBot},
		{"gitea actions bot", Input{Forge: "gitea", Author: "gitea-actions", Body: "Bumps x"}, Unknown, RuleBot},
		{"forgejo actions bot", Input{Forge: "gitea", Author: "Forgejo-Actions", Body: "Bumps x"}, Unknown, RuleBot},
		{"github suffix on gitea", Input{Forge: "gitea", Author: "renovate[bot]", Body: "Bumps x"}, Unknown, RuleBot},
		{"gitlab-style name on github is human", Input{Author: "project_7_bot", Body: "by hand"}, Human, RuleDefaultHuman},
		{"gitea human", Input{Forge: "gitea", Author: "clubanderson", Body: "by hand"}, Human, RuleDefaultHuman},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			kind, rule := Explain(tc.in)
			if kind != tc.kind || rule != tc.rule {
				t.Fatalf("Explain = (%q, %s) want (%q, %s)", kind, rule, tc.kind, tc.rule)
			}
		})
	}
}
