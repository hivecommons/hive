package automerge

// Renovate's "Artifact update problem" comment by the PR's own bot holds a
// trusted bot's Renovate PR for the owner (projectbluefin/testsuite#1230).

import (
	"context"
	"strings"
	"testing"

	gh "github.com/google/go-github/v72/github"

	"github.com/hivecommons/hive/pkg/stageengine/prstage"
)

const (
	renovateTestBot      = "mergeraptor[bot]"
	renovateFooter       = "\n\n---\n\nThis PR has been generated by [Mend Renovate CLI](https://redirect.github.com/renovatebot/renovate)."
	renovateDisabledLine = "🚦 **Automerge**: Disabled by config. Please merge this manually once you are satisfied."
	renovateEnabledLine  = "🚦 **Automerge**: Enabled."
	renovateArtifactBody = "### ⚠️ Artifact update problem\n\nRenovate failed to update an artifact related to this branch. You probably do not want to merge this PR as-is."
)

func TestRenovateArtifactProblemComment(t *testing.T) {
	comment := func(login, body string) *gh.IssueComment {
		return &gh.IssueComment{User: &gh.User{Login: gh.Ptr(login)}, Body: gh.Ptr(body)}
	}
	for _, tc := range []struct {
		name     string
		comments []*gh.IssueComment
		want     bool
	}{
		{"the bot's artifact comment", []*gh.IssueComment{comment(renovateTestBot, renovateArtifactBody)}, true},
		{"login case differs", []*gh.IssueComment{comment("Mergeraptor[bot]", renovateArtifactBody)}, true},
		{"older heading without the variation selector", []*gh.IssueComment{comment(renovateTestBot, "### ⚠ Artifact update problem\n\n…")}, true},
		{"someone else posted it", []*gh.IssueComment{comment("mallory", renovateArtifactBody)}, false},
		{"the words outside a heading", []*gh.IssueComment{comment(renovateTestBot, "No artifact update problem this time.")}, false},
		{"no comments", nil, false},
		{"nil entry", []*gh.IssueComment{nil}, false},
	} {
		if got := renovateArtifactProblemComment(tc.comments, renovateTestBot); got != tc.want {
			t.Errorf("%s: renovateArtifactProblemComment = %v, want %v", tc.name, got, tc.want)
		}
	}
	if renovateArtifactProblemComment([]*gh.IssueComment{comment(renovateTestBot, renovateArtifactBody)}, "") {
		t.Error("an empty PR author must match nothing")
	}
}

func TestIsRenovatePR(t *testing.T) {
	pr := func(ref, body string) *gh.PullRequest {
		return &gh.PullRequest{Head: &gh.PullRequestBranch{Ref: gh.Ptr(ref)}, Body: gh.Ptr(body)}
	}
	for _, tc := range []struct {
		name string
		pr   *gh.PullRequest
		want bool
	}{
		{"renovate branch", pr("renovate/typescript-7.x", ""), true},
		{"renovate footer", pr("deps/typescript", renovateFooter), true},
		{"dependabot", pr("dependabot/npm_and_yarn/typescript-7.0.0", "Bumps typescript."), false},
		{"nil", nil, false},
	} {
		if got := isRenovatePR(tc.pr); got != tc.want {
			t.Errorf("%s: isRenovatePR = %v, want %v", tc.name, got, tc.want)
		}
	}
}

// The sweep holds a trusted bot's Renovate PR on its bot's artifact comment
// and merges it otherwise, whatever the description says about automerge.
// The App's own PR and a non-Renovate bot's PR are never checked.
func TestTrustedBotLaneRenovateArtifactGate(t *testing.T) {
	artifact := []map[string]any{{"id": 1, "user": map[string]any{"login": renovateTestBot}, "body": renovateArtifactBody}}
	forged := []map[string]any{{"id": 2, "user": map[string]any{"login": "mallory"}, "body": renovateArtifactBody}}
	for _, tc := range []struct {
		name       string
		author     string
		body       string
		comments   []map[string]any
		wantReason string
	}{
		{name: "automerge disabled, no comment", author: renovateTestBot, body: renovateDisabledLine + renovateFooter},
		{name: "artifact problem", author: renovateTestBot, body: renovateEnabledLine + renovateFooter, comments: artifact, wantReason: prstage.AutoMergeReasonRenovateArtifactProblem},
		{name: "artifact problem, automerge disabled", author: renovateTestBot, body: renovateDisabledLine + renovateFooter, comments: artifact, wantReason: prstage.AutoMergeReasonRenovateArtifactProblem},
		{name: "artifact comment by someone else", author: renovateTestBot, body: renovateEnabledLine + renovateFooter, comments: forged},
		{name: "automerge enabled, no comment", author: renovateTestBot, body: renovateEnabledLine + renovateFooter},
		{name: "not a Renovate PR", author: "dependabot[bot]", body: renovateDisabledLine, comments: artifact},
		{name: "the App's own PR", author: testHiveAppBotLogin, body: renovateDisabledLine + renovateFooter, comments: artifact},
	} {
		t.Run(tc.name, func(t *testing.T) {
			merges := 0
			api := newSelfSweepGuardAPI(t, selfSweepFixture{author: tc.author, body: tc.body, issueComments: tc.comments, mergeApplied: true, mergeCalls: &merges})
			defer api.Close()
			c := newAutoMergeSweepClient(api.URL)
			c.trustedBotAuthors = func() map[string]bool { return map[string]bool{renovateTestBot: true, "dependabot[bot]": true} }
			event, reason, err := c.trySweepSelfAuthoredPR(context.Background(), "acme/widget", "acme", "widget", 7, true)
			if err != nil {
				t.Fatalf("trySweepSelfAuthoredPR error: %v", err)
			}
			if reason != tc.wantReason {
				t.Fatalf("reason = %q, want %q", reason, tc.wantReason)
			}
			wantMerges := 1
			if tc.wantReason != "" {
				wantMerges = 0
			}
			if merges != wantMerges || (wantMerges == 0) != (event.MergeSHA == "") {
				t.Fatalf("merges = %d event = %+v, want %d merge(s)", merges, event, wantMerges)
			}
		})
	}
}

// The reason parks at 090 under an owner-merge rule no approval releases,
// with its own code and cause.
func TestRenovateArtifactProblemIsOwnerMergeRule(t *testing.T) {
	for reason, code := range map[string]string{
		prstage.AutoMergeReasonRenovateArtifactProblem: prstage.HumanMergeReasonRenovateArtifactProblem,
	} {
		if !manualMergeRuleReasonFor(reason, false) {
			t.Errorf("%s: not a manual-merge rule", reason)
		}
		if got := prstage.HumanMergeReason(reason); got != code || !prstage.IsOwnerMergeCode(got) {
			t.Errorf("%s: HumanMergeReason = %q, want owner-merge code %q", reason, got, code)
		}
		if cause := decisionCause(reason); cause == "" || !strings.Contains(cause, "Renovate") {
			t.Errorf("%s: decisionCause = %q, want the Renovate cause", reason, cause)
		}
		if !prstage.IsOwnerMergeReason(reason + ":human-approved@castrojo") {
			t.Errorf("%s: an approval suffix must not drop the owner-merge rule", reason)
		}
	}
}
