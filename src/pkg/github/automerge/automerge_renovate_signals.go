package automerge

// Renovate tells a person, in its own words, when one of its PRs should not
// merge unattended: the PR description says automerge is disabled by the
// repository's Renovate config (a major under `automerge: false`), or the
// bot comments that it failed to update an artifact such as a lock file.
// The trusted-bot lane merges on green CI alone, so without these checks it
// merged both kinds (projectbluefin/testsuite#1230: a TypeScript major whose
// package-lock.json Renovate could not update, merged three minutes after
// the "Artifact update problem" comment). The comment always holds the PR;
// the description line holds it only when
// auto_merge.trusted_bot_honor_renovate_automerge is on (default off: many
// Renovate configs set `automerge: false` so that the hive does the
// merging). Either hold parks the PR at 090 for the owner's merge click,
// like a breaking change: no approval releases it.

import (
	"context"
	"regexp"
	"strings"

	gh "github.com/google/go-github/v72/github"

	hgithub "github.com/hivecommons/hive/pkg/github"
	"github.com/hivecommons/hive/pkg/stageengine/prstage"
)

const (
	autoMergeReasonRenovateAutomergeDisabled = prstage.AutoMergeReasonRenovateAutomergeDisabled
	autoMergeReasonRenovateArtifactProblem   = prstage.AutoMergeReasonRenovateArtifactProblem
	// autoMergeReasonRenovateCommentsEvidence: the comments could not be
	// read, so the lane does not merge this pass.
	autoMergeReasonRenovateCommentsEvidence = "renovate-comments-evidence"
)

var (
	// renovateAutomergeDisabledRE matches the line Renovate writes in a PR
	// description when automerge is off for the update:
	// "🚦 **Automerge**: Disabled by config. Please merge this manually …"
	// (or "Disabled because a matching PR was automerged previously.").
	renovateAutomergeDisabledRE = regexp.MustCompile(`(?mi)^[^\S\n]*(?:🚦[^\S\n]*)?\*\*Automerge\*\*:[^\S\n]*Disabled\b`)
	// renovateArtifactProblemRE matches the heading of the comment Renovate
	// posts when it cannot update an artifact on the branch:
	// "### ⚠️ Artifact update problem". Renovate deletes that comment once a
	// later run updates the artifacts, so its presence is current.
	renovateArtifactProblemRE = regexp.MustCompile(`(?mi)^#{1,6}[^\n]*\bArtifact update problem\b`)
)

// renovateFooterLink is in the footer of every Renovate PR description
// ("generated by [Mend Renovate](https://github.com/renovatebot/renovate)",
// "[Renovate Bot](…renovatebot/renovate)").
const renovateFooterLink = "renovatebot/renovate"

// isRenovatePR reports whether pr was opened by Renovate, whatever account
// it runs as: a `renovate/` head branch (Renovate's default prefix) or
// Renovate's footer link in the description. Only such a PR is checked, so
// the trusted-bot lane reads no comments for Dependabot or other bots.
func isRenovatePR(pr *gh.PullRequest) bool {
	if pr == nil {
		return false
	}
	return strings.HasPrefix(strings.TrimSpace(pr.GetHead().GetRef()), "renovate/") || strings.Contains(pr.GetBody(), renovateFooterLink)
}

// renovateAutomergeDisabled reports whether a PR description carries
// Renovate's "Automerge: Disabled" line.
func renovateAutomergeDisabled(body string) bool {
	return renovateAutomergeDisabledRE.MatchString(body)
}

// renovateArtifactProblemComment reports whether one of comments is an
// "Artifact update problem" comment written by author, the bot that opened
// the PR. A comment by anyone else does not count.
func renovateArtifactProblemComment(comments []*gh.IssueComment, author string) bool {
	author = strings.TrimSpace(author)
	if author == "" {
		return false
	}
	for _, cm := range comments {
		if cm == nil || !strings.EqualFold(hgithub.SafeGetLogin(cm.GetUser()), author) {
			continue
		}
		if renovateArtifactProblemRE.MatchString(cm.GetBody()) {
			return true
		}
	}
	return false
}

// trustedBotHonorsRenovateAutomerge is the live
// auto_merge.trusted_bot_honor_renovate_automerge switch; nil means off.
func (c *Engine) trustedBotHonorsRenovateAutomerge() bool {
	return c.trustedBotHonorRenovateAutomerge != nil && c.trustedBotHonorRenovateAutomerge()
}

// renovateManualMergeGate holds a trusted-bot lane PR that Renovate itself
// says a person should merge. It runs only for a Renovate PR on the
// trusted-bot lane and only for a head that is otherwise mergeable, so the
// comment read is spent on PRs about to merge. The description check needs
// no API call and goes first; the comment check runs whatever the switch
// says.
func (c *Engine) renovateManualMergeGate(ctx context.Context, displayRepo, owner, repo string, pr *gh.PullRequest, lane string) (string, error) {
	if lane != laneTrustedBot || !isRenovatePR(pr) {
		return "", nil
	}
	number, head := pr.GetNumber(), pr.GetHead().GetSHA()
	author := hgithub.SafeGetLogin(pr.GetUser())
	if c.trustedBotHonorsRenovateAutomerge() && renovateAutomergeDisabled(pr.GetBody()) {
		c.logRenovateHold(displayRepo, owner, repo, number, head, author, autoMergeReasonRenovateAutomergeDisabled)
		return autoMergeReasonRenovateAutomergeDisabled, nil
	}
	var comments []*gh.IssueComment
	opts := &gh.IssueListCommentsOptions{ListOptions: gh.ListOptions{PerPage: 100}}
	for {
		page, resp, err := c.gh.Issues.ListComments(hgithub.WithRESTCaller(ctx, "hive:automerge_sweep"), owner, repo, number, opts)
		if err != nil {
			return autoMergeReasonRenovateCommentsEvidence, err
		}
		comments = append(comments, page...)
		if resp == nil || resp.NextPage == 0 {
			break
		}
		opts.Page = resp.NextPage
	}
	if renovateArtifactProblemComment(comments, author) {
		c.logRenovateHold(displayRepo, owner, repo, number, head, author, autoMergeReasonRenovateArtifactProblem)
		return autoMergeReasonRenovateArtifactProblem, nil
	}
	return "", nil
}

func (c *Engine) logRenovateHold(displayRepo, owner, repo string, number int, head, author, reason string) {
	if c.markTerminalHoldLogged(owner, repo, number, head, reason) {
		c.info("trusted-bot lane: Renovate asks for a manual merge; leaving it to the owner",
			"tier", laneTrustedBot, "repo", displayRepo, "pr", number, "head", head, "author", author, "reason", reason)
	}
}
