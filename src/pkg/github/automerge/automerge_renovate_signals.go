package automerge

// Renovate tells a person, in its own words, when one of its branches is
// broken: it comments "⚠️ Artifact update problem … You probably do not want
// to merge this PR as-is" when it could not update a lock file or other
// artifact. The trusted-bot lane merges on green CI alone, so without this
// check it merged such a branch (projectbluefin/testsuite#1230: a TypeScript
// major merged three minutes after that comment, with package.json and
// package-lock.json out of step). The hold parks the PR at 090 for the
// owner's merge click, like a breaking change: no approval releases it.
// Renovate deletes the comment once a later run updates the artifacts, and
// the PR then merges as usual.

import (
	"context"
	"regexp"
	"strings"

	gh "github.com/google/go-github/v72/github"

	hgithub "github.com/hivecommons/hive/pkg/github"
	"github.com/hivecommons/hive/pkg/stageengine/prstage"
)

const (
	autoMergeReasonRenovateArtifactProblem = prstage.AutoMergeReasonRenovateArtifactProblem
	// autoMergeReasonRenovateCommentsEvidence: the comments could not be
	// read, so the lane does not merge this pass.
	autoMergeReasonRenovateCommentsEvidence = "renovate-comments-evidence"
	// renovateFooterLink is in the footer of every Renovate PR description
	// ("generated by [Mend Renovate](https://github.com/renovatebot/renovate)",
	// "[Renovate Bot](…renovatebot/renovate)").
	renovateFooterLink = "renovatebot/renovate"
)

// renovateArtifactProblemRE matches the heading of the comment Renovate
// posts when it cannot update an artifact on the branch:
// "### ⚠️ Artifact update problem".
var renovateArtifactProblemRE = regexp.MustCompile(`(?mi)^#{1,6}[^\n]*\bArtifact update problem\b`)

// isRenovatePR reports whether pr was opened by Renovate, whatever account
// it runs as: a `renovate/` head branch (Renovate's default prefix) or
// Renovate's footer link in the description. Only such a PR is checked, so
// the trusted-bot lane reads no comments for Dependabot or other bots.
func isRenovatePR(pr *gh.PullRequest) bool {
	if pr == nil {
		return false
	}
	return strings.HasPrefix(strings.TrimSpace(pr.GetHead().GetRef()), "renovate/") || strings.Contains(pr.GetBody(), renovateFooterLink)
}

// renovateArtifactProblemComment reports whether one of comments is an
// "Artifact update problem" comment written by author, the bot that opened
// the PR. A comment by anyone else does not count.
func renovateArtifactProblemComment(comments []*gh.IssueComment, author string) bool {
	author = strings.TrimSpace(author)
	if author == "" {
		return false
	}
	for _, cm := range comments {
		if cm == nil || !strings.EqualFold(hgithub.SafeGetLogin(cm.GetUser()), author) {
			continue
		}
		if renovateArtifactProblemRE.MatchString(cm.GetBody()) {
			return true
		}
	}
	return false
}

// renovateArtifactGate holds a trusted-bot lane Renovate PR whose bot
// reported an artifact update problem. It runs only for a Renovate PR on the
// trusted-bot lane and only for a head that is otherwise mergeable, so the
// comment read is spent on PRs about to merge.
func (c *Engine) renovateArtifactGate(ctx context.Context, displayRepo, owner, repo string, pr *gh.PullRequest, lane string) (string, error) {
	if lane != laneTrustedBot || !isRenovatePR(pr) {
		return "", nil
	}
	number, head := pr.GetNumber(), pr.GetHead().GetSHA()
	author := hgithub.SafeGetLogin(pr.GetUser())
	var comments []*gh.IssueComment
	opts := &gh.IssueListCommentsOptions{ListOptions: gh.ListOptions{PerPage: 100}}
	for {
		page, resp, err := c.gh.Issues.ListComments(hgithub.WithRESTCaller(ctx, "hive:automerge_sweep"), owner, repo, number, opts)
		if err != nil {
			return autoMergeReasonRenovateCommentsEvidence, err
		}
		comments = append(comments, page...)
		if resp == nil || resp.NextPage == 0 {
			break
		}
		opts.Page = resp.NextPage
	}
	if !renovateArtifactProblemComment(comments, author) {
		return "", nil
	}
	if c.markTerminalHoldLogged(owner, repo, number, head, autoMergeReasonRenovateArtifactProblem) {
		c.info("trusted-bot lane: Renovate reported an artifact update problem; leaving the PR to the owner",
			"tier", laneTrustedBot, "repo", displayRepo, "pr", number, "head", head, "author", author, "reason", autoMergeReasonRenovateArtifactProblem)
	}
	return autoMergeReasonRenovateArtifactProblem, nil
}
