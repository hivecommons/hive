#!/bin/sh
# install-copilot-exec-shim.sh — wrap the Copilot CLI platform binary so it is
# started through the glibc dynamic loader instead of execve'd directly.
#
# Why (hivecommons/hive#17729): the @github/copilot platform package ships a
# Bun single-file executable — an ELF64 ET_EXEC with a 0x1000-aligned appended
# JS segment after 0x10000-aligned code/data LOADs. Linux 6.12 (seen on OKE
# UEK8 6.12.0-207, aarch64) rejects that layout in binfmt_elf with ENOEXEC
# ("Exec format error"); the npm-loader shim's sh fallback then "runs" the
# ELF as a script and every copilot agent crash-loops. glibc's ld.so maps the
# very same file without complaint, so `ld.so <binary>` is a drop-in.
#
# Build-time only. Idempotent. Tolerant of a missing copilot install (the
# Dockerfile layer that installs it is itself tolerant). Usage:
#   install-copilot-exec-shim.sh [npm-global-root]
set -eu

ROOT="${1:-$(npm root -g 2>/dev/null || echo /usr/local/lib/node_modules)}"
PKG_DIR="$ROOT/@github/copilot/node_modules/@github"

# Arch → loader, resolved at BUILD time for the target arch. The wrapper falls
# back to a direct exec when the loader is absent (musl, unusual distros).
case "$(uname -m)" in
  aarch64|arm64) LDSO=/lib/ld-linux-aarch64.so.1 ;;
  x86_64|amd64)  LDSO=/lib64/ld-linux-x86-64.so.2 ;;
  *)             LDSO="" ;;
esac

if [ ! -d "$PKG_DIR" ]; then
  echo "install-copilot-exec-shim: no @github/copilot platform package under $PKG_DIR — skipping"
  exit 0
fi

installed=0
for dir in "$PKG_DIR"/copilot-linux-*; do
  [ -d "$dir" ] || continue
  bin="$dir/copilot"
  real="$dir/copilot.real"
  if [ -f "$real" ] && head -c 2 "$bin" 2>/dev/null | grep -q '#!'; then
    echo "install-copilot-exec-shim: $bin already wrapped"
    installed=$((installed + 1))
    continue
  fi
  if [ ! -f "$bin" ]; then
    echo "install-copilot-exec-shim: $bin missing — skipping"
    continue
  fi
  mv "$bin" "$real"
  cat > "$bin" <<EOF
#!/bin/sh
# Generated by bin/install-copilot-exec-shim.sh (hivecommons/hive#17729).
# Linux 6.12 rejects this ET_EXEC Bun binary with ENOEXEC; glibc's ld.so maps
# it fine, so start it through the loader. HIVE_COPILOT_DIRECT_EXEC=1 forces
# the plain exec (debugging only).
REAL="$real"
LDSO="$LDSO"
if [ -z "\${HIVE_COPILOT_DIRECT_EXEC:-}" ] && [ -n "\$LDSO" ] && [ -x "\$LDSO" ]; then
  exec "\$LDSO" "\$REAL" "\$@"
fi
exec "\$REAL" "\$@"
EOF
  chown root:root "$bin" "$real" 2>/dev/null || true
  chmod 0755 "$bin" "$real"
  echo "install-copilot-exec-shim: wrapped $bin via ${LDSO:-direct exec}"
  installed=$((installed + 1))
done

if [ "$installed" -eq 0 ]; then
  echo "install-copilot-exec-shim: no copilot-linux-* platform binary found — skipping"
  exit 0
fi

# Prove the wrapped CLI starts, through the npm shim, the way an agent runs it.
if ! copilot --version >/dev/null 2>&1; then
  echo "install-copilot-exec-shim: WARNING: 'copilot --version' failed after wrapping" >&2
  exit 0
fi
echo "install-copilot-exec-shim: copilot --version OK ($(copilot --version 2>/dev/null | head -1))"
