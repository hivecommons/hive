			if _, err := os.Stat(signal); err == nil {
				write(os.Getenv("HIVE_REPAIR_TEST_TARGET"), "escaped-tool-authored\n")
				write(os.Getenv("HIVE_REPAIR_TEST_ACK"), "written\n")
				return
			}
