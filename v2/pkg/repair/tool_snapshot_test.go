func TestExactPreparationReplayRecoveryRequiresAuditedRetry(t *testing.T) {
	t.Setenv("GO_WANT_REPAIR_TOOL_MUTATION_HELPER", "1")
	repository, remote := seedGitRepository(t)
	worktreeRoot := filepath.Join(t.TempDir(), "worktrees")
	worktree := filepath.Join(worktreeRoot, "recovery")
	branch := "hive/repair-recovery-a4"
	if err := prepareWorktree(context.Background(), repository, worktree, branch, "main", "", remote); err != nil {
		t.Fatal(err)
	}
	command := repairToolHelperCommand("generate-build")
	if err := runRepairCommand(context.Background(), worktree, command, time.Minute, nil, "preparation"); err != nil {
		t.Fatal(err)
	}
	patchOutput := `HIVE_PATCH_BEGIN
diff --git a/src/value.txt b/src/value.txt
--- a/src/value.txt
+++ b/src/value.txt
@@ -1 +1 @@
-broken
+recovered exact patch
HIVE_PATCH_END`
	priorSummary := patchOutput + priorRejectedPatchMarker + "repair changed build/lib/service/metrics.py outside the configured repair allowlist"
	stateDir := filepath.Join(t.TempDir(), "state")
	state, _ := NewStore(stateDir)
	fingerprint := "owner/repo:replay-recovery"
	attempt := Attempt{
		Repository: "owner/repo", RepositoryFingerprint: fingerprint, Attempt: 4, Branch: branch, Worktree: worktree,
		Stage: StageModelRunning, Provider: "codex", AttemptCounted: false, ModelInvocationID: "ambiguous-fourth",
		PriorModelSummary: priorSummary, StartedAt: time.Now().UTC(),
	}
	if err := state.Put(attempt); err != nil {
		t.Fatal(err)
	}
	lifecycle := &fakeLifecycle{}
	pulls := &fakePRClient{state: state}
	worker := &Worker{
		Config: Config{
			RepositoryDir: repository, WorktreeRoot: worktreeRoot, BaseBranch: "main", ExpectedRemoteURL: remote, Policy: standardRepairPolicy(),
			AllowedRepairPaths: []string{"src/**"}, PreparationCommands: []Command{command},
			ValidationCommands: []Command{{Name: "git", Args: []string{"diff", "--check"}}}, ModelTimeout: time.Minute, CommandTimeout: time.Minute,
		},
		Provider: CodexProvider{Command: os.Args[0]}, State: state, Lifecycle: lifecycle, GitHub: pulls,
	}
	finding := standardRepairFinding(fingerprint)
	finding.Status, finding.RepairAttempts = visualhive.StatusRepairRunning, 3
	_, runErr := worker.Run(context.Background(), finding)
	var paused *ResumableFailureError
	if !errors.As(runErr, &paused) || paused.Class != FailurePatchEngine || paused.Attempt != 4 || !strings.Contains(runErr.Error(), "requires explicit retry authorization") {
		t.Fatalf("exact replay recovery did not pause for audited retry: %v", runErr)
	}
	recovered, _ := state.Get(fingerprint)
	if !recovered.AttemptCounted || recovered.Stage != StageFailed || recovered.ResumeStage != StageModelComplete || recovered.RecoveredPatchAttempt != 3 || recovered.RecoveredPatchSHA256 == "" || recovered.RecoveredProviderSHA256 == "" || recovered.PreparationReplayProof == "" || recovered.ModelPatch == "" || recovered.RecoveredPatchAuthorized || lifecycle.starts != 1 || pulls.calls != 0 {
		t.Fatalf("recovery provenance/counting checkpoint is incomplete: attempt=%+v lifecycle=%+v pulls=%d", recovered, lifecycle, pulls.calls)
	}
	if _, err := state.ResumeRetry(RetryRequest{
		RepositoryFingerprint: fingerprint, ExpectedRecurrence: 0, ExpectedAttempt: 4, ExpectedFailureClass: FailurePatchEngine,
		ExpectedFailureID: recovered.LastFailureID, Actor: "operator", Reason: "missing historical provider attestation",
	}); err == nil || !strings.Contains(err.Error(), "must attest") {
		t.Fatalf("recovery retry accepted no historical provider attestation: %v", err)
	}
	if _, err := state.ResumeRetry(RetryRequest{
		RepositoryFingerprint: fingerprint, ExpectedRecurrence: 0, ExpectedAttempt: 4, ExpectedFailureClass: FailurePatchEngine,
		ExpectedFailureID: recovered.LastFailureID, Actor: "operator", Reason: strings.Repeat("x", 5_000) + recoveredProviderAttestation(recovered) + strings.Repeat("y", 5_000),
	}); err == nil || !strings.Contains(err.Error(), "must attest") {
		t.Fatalf("recovery retry accepted an attestation omitted from durable bounded reason: %v", err)
	}
	longUnicodeReason := strings.Repeat("界", 3_000) + string([]byte{0xff, 0xfe}) + "; verified exact detached preparation replay and recovered patch digest; " + recoveredProviderAttestation(recovered)
	if _, err := state.ResumeRetry(RetryRequest{
		RepositoryFingerprint: fingerprint, ExpectedRecurrence: 0, ExpectedAttempt: 4, ExpectedFailureClass: FailurePatchEngine,
		ExpectedFailureID: recovered.LastFailureID, Actor: "operator", Reason: longUnicodeReason,
	}); err != nil {
		t.Fatal(err)
	}
	reloadedState, err := NewStore(stateDir)
	if err != nil {
		t.Fatalf("reopen store after a bounded multibyte retry reason: %v", err)
	}
	state = reloadedState
	worker.State = reloadedState
	pulls.state = reloadedState
	authorized, _ := reloadedState.Get(fingerprint)
	if !authorized.RecoveredPatchAuthorized || !recoveredPatchDigestMatches(authorized) || authorized.Stage != StageModelComplete || !utf8.ValidString(authorized.RetryReason) {
		t.Fatalf("exact retry did not durably authorize the recovered patch: %+v", authorized)
	}
	finding.RepairAttempts, finding.Branch = 4, branch
	result, err := worker.Run(context.Background(), finding)
	if err != nil {
		t.Fatal(err)
	}
	if pulls.calls != 1 || result.PRNumber != 17 || strings.TrimSpace(gitOutput(t, remote, "show", result.Branch+":src/value.txt")) != "recovered exact patch" {
		t.Fatalf("audited same-attempt recovery did not finish exact patch: result=%+v pulls=%d", result, pulls.calls)
	}
	audit, err := os.ReadFile(filepath.Join(stateDir, "repair-retry-audit.jsonl"))
	if err != nil || !strings.Contains(string(audit), recovered.LastFailureID) || !strings.Contains(string(audit), "verified exact detached preparation replay") || !strings.Contains(string(audit), recovered.RecoveredProviderSHA256) {
		t.Fatalf("recovery authorization was not durably audited: %s err=%v", audit, err)
	}
}
